// Why: the std.math intrinsics must agree in the evaluator and in native code,
// and only a shared vector file can show both give the oracle's answers.
// What: TestNativeVectors, which writes std/math/tests_intrinsics_vec.mk
// and fails when the checked-in file differs (-update rewrites it). The
// direct tests of the evaluator's Go definitions are in intrinsic_math_test.go.
// How: Go oracles (math/big for the overflow, saturating and wide forms,
// ECMA-262's ToInt32 and ToUint32 steps) over edge values and random bit
// patterns. Each generated check function runs in a const, computed by the
// evaluator, and in a test block run natively by `mk test --std=std.math`.

package eval

import (
	"fmt"
	"math"
	"math/big"
	"math/rand"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// vecInt is one integer type of the generated vectors.
type vecInt struct {
	name   string
	w      int
	signed bool
}

var vecInts = []vecInt{{"i8", 1, true}, {"i16", 2, true}, {"i32", 4, true}, {"i64", 8, true}, {"int", 8, true},
	{"u8", 1, false}, {"u16", 2, false}, {"u32", 4, false}, {"u64", 8, false}, {"uint", 8, false}}

// lit spells the w-byte pattern x as a Mk literal of the type.
func (v vecInt) lit(x uint64) string {
	if v.signed {
		s := sext(x&mask(v.w), v.w)
		if s == math.MinInt64 {
			return "-9223372036854775807 - 1"
		}
		return fmt.Sprint(s)
	}
	return fmt.Sprint(x & mask(v.w))
}

func joinf(n int, f func(i int) string) string {
	var b strings.Builder
	for i := 0; i < n; i++ {
		if i > 0 {
			b.WriteString(", ")
		}
		if i > 0 && i%8 == 0 {
			b.WriteString("\n    ")
		}
		b.WriteString(f(i))
	}
	return b.String()
}

func mathVectors() string {
	rng := rand.New(rand.NewSource(1922))
	var b strings.Builder
	b.WriteString(`// Code generated by internal/eval's TestNativeVectors (go test
// ./internal/eval -run TestNativeVectors -update); DO NOT EDIT.
//
// std.math's intrinsics against Go oracles (math/big; ECMA-262's
// ToInt32 and ToUint32 steps written in Go), edge values and random bit
// patterns. Each check function runs in a const, computed by the
// evaluator at compile time, and in a test block, run natively: "mk test
// --std=std.math".

`)
	// Overflow-flag forms.
	edges := []uint64{0, 1, 2, 0x7f, 0x80, 0xff, 0x7fff, 0x8000, 0xffff, 0x7fffffff, 0x80000000, 0xffffffff, 1<<63 - 1, 1 << 63, ^uint64(0)}
	for _, v := range vecInts {
		var as, bs []uint64
		for i := 0; i < 24; i++ {
			as = append(as, edges[rng.Intn(len(edges))]&mask(v.w))
			bs = append(bs, edges[rng.Intn(len(edges))]&mask(v.w))
		}
		for i := 0; i < 16; i++ {
			as = append(as, rng.Uint64()&mask(v.w))
			bs = append(bs, rng.Uint64()&mask(v.w))
		}
		n := len(as)
		up := strings.ToUpper(v.name[:1]) + v.name[1:]
		fmt.Fprintf(&b, "const OvA%s: [%d]%s = [%s]\n", up, n, v.name, joinf(n, func(i int) string { return v.lit(as[i]) }))
		fmt.Fprintf(&b, "const OvB%s: [%d]%s = [%s]\n", up, n, v.name, joinf(n, func(i int) string { return v.lit(bs[i]) }))
		for _, op := range []struct {
			name  string
			id    ovfOp
			exact func(x, y *big.Int) *big.Int
		}{{"Add", ovfAdd, func(x, y *big.Int) *big.Int { return new(big.Int).Add(x, y) }},
			{"Sub", ovfSub, func(x, y *big.Int) *big.Int { return new(big.Int).Sub(x, y) }},
			{"Mul", ovfMul, func(x, y *big.Int) *big.Int { return new(big.Int).Mul(x, y) }}} {
			vals := make([]uint64, n)
			ovs := make([]bool, n)
			for i := range as {
				wv, fits := bigWrap(op.exact(bigOf(as[i], v.w, v.signed), bigOf(bs[i], v.w, v.signed)), v.w, v.signed)
				vals[i], ovs[i] = wv, !fits
			}
			fmt.Fprintf(&b, "const Ov%sV%s: [%d]%s = [%s]\n", op.name, up, n, v.name, joinf(n, func(i int) string { return v.lit(vals[i]) }))
			fmt.Fprintf(&b, "const Ov%sO%s: [%d]bool = [%s]\n", op.name, up, n, joinf(n, func(i int) string { return fmt.Sprint(ovs[i]) }))
		}
		fmt.Fprintf(&b, `
VecOv%[1]s(): bool {
    for i in 0..%[2]d {
        a := %[3]sOverflow[%[4]s](OvA%[1]s[i], OvB%[1]s[i])
        if a.value != OvAddV%[1]s[i] || a.overflow != OvAddO%[1]s[i] {
            return false
        }
        s := SubOverflow[%[4]s](OvA%[1]s[i], OvB%[1]s[i])
        if s.value != OvSubV%[1]s[i] || s.overflow != OvSubO%[1]s[i] {
            return false
        }
        m := MulOverflow[%[4]s](OvA%[1]s[i], OvB%[1]s[i])
        if m.value != OvMulV%[1]s[i] || m.overflow != OvMulO%[1]s[i] {
            return false
        }
    }
    return true
}

const EvalOv%[1]s: bool = VecOv%[1]s()

test "overflow flags of %[4]s, natively and in the evaluator" {
    Assert(EvalOv%[1]s)
    Assert(VecOv%[1]s())
}

`, up, n, "Add", v.name)
	}
	// WrapI32 and WrapU32.
	fe := []float64{0, math.Copysign(0, -1), 0.5, -0.5, 1, -1, 1.9, -1.9, 2147483647, 2147483648, -2147483648, -2147483649,
		4294967295, 4294967296, 4294967297.5, -4294967297.5, 1e10, -1e10, 9007199254740991, 9007199254740993, 1 << 63, 1e300, -1e300,
		math.MaxFloat64, math.SmallestNonzeroFloat64, math.Inf(1), math.Inf(-1), math.NaN(), 0x1p52, 0x1p53 + 2, 0x1p84 + 0x1p32, -0x1p84 - 0x1p40}
	var wb []uint64
	for _, x := range fe {
		wb = append(wb, math.Float64bits(x))
	}
	for i := 0; i < 32; i++ {
		x := rng.Uint64()
		if i%2 == 0 {
			x = math.Float64bits((rng.Float64() - 0.5) * math.Ldexp(1, rng.Intn(90)))
		}
		wb = append(wb, x)
	}
	n := len(wb)
	fmt.Fprintf(&b, "const WrapIn: [%d]u64 = [%s]\n", n, joinf(n, func(i int) string { return fmt.Sprintf("0x%x", wb[i]) }))
	fmt.Fprintf(&b, "const WrapOutU: [%d]u32 = [%s]\n", n, joinf(n, func(i int) string { return fmt.Sprint(ecmaToUint32(math.Float64frombits(wb[i]))) }))
	fmt.Fprintf(&b, "const WrapOutI: [%d]i32 = [%s]\n", n, joinf(n, func(i int) string { return fmt.Sprint(ecmaToInt32(math.Float64frombits(wb[i]))) }))
	fmt.Fprintf(&b, `
VecWrap(): bool {
    for i in 0..%d {
        x := f64.FromBits(WrapIn[i])
        if WrapU32(x) != WrapOutU[i] || WrapI32(x) != WrapOutI[i] {
            return false
        }
    }
    return true
}

const EvalWrap: bool = VecWrap()

test "WrapI32 and WrapU32 are ECMA-262's ToInt32 and ToUint32, natively and in the evaluator" {
    Assert(EvalWrap)
    Assert(VecWrap())
}

`, n)
	// CastSat and CastSatF32, per type.
	ce := []float64{0, math.Copysign(0, -1), -0.9, 0.9, 127.5, 128, -128.5, -129, 255.9, 256, 32767.5, 65535, 65536, 2147483647.5, 4294967296,
		1e19, -1e19, 0x1p63, -0x1p63, 0x1p64, math.Inf(1), math.Inf(-1), math.NaN()}
	var cb []uint64
	for _, x := range ce {
		cb = append(cb, math.Float64bits(x))
	}
	for i := 0; i < 16; i++ {
		cb = append(cb, math.Float64bits((rng.Float64()-0.5)*math.Ldexp(1, rng.Intn(70))))
	}
	n = len(cb)
	fmt.Fprintf(&b, "const SatIn: [%d]u64 = [%s]\n", n, joinf(n, func(i int) string { return fmt.Sprintf("0x%x", cb[i]) }))
	fmt.Fprintf(&b, "const SatIn32: [%d]u32 = [%s]\n", n, joinf(n, func(i int) string {
		return fmt.Sprintf("0x%x", math.Float32bits(float32(math.Float64frombits(cb[i]))))
	}))
	for _, v := range vecInts {
		up := strings.ToUpper(v.name[:1]) + v.name[1:]
		sat := func(x float64) uint64 {
			if math.IsNaN(x) {
				return 0
			}
			var i *big.Int
			if math.IsInf(x, 0) {
				i = new(big.Int).Lsh(big.NewInt(int64(math.Copysign(1, x))), 100)
			} else {
				i, _ = new(big.Float).SetFloat64(math.Trunc(x)).Int(nil)
			}
			lo, hi := big.NewInt(0), new(big.Int).Sub(new(big.Int).Lsh(big.NewInt(1), uint(8*v.w)), big.NewInt(1))
			if v.signed {
				hi = new(big.Int).Sub(new(big.Int).Lsh(big.NewInt(1), uint(8*v.w-1)), big.NewInt(1))
				lo = new(big.Int).Neg(new(big.Int).Add(hi, big.NewInt(1)))
			}
			if i.Cmp(lo) < 0 {
				i = lo
			}
			if i.Cmp(hi) > 0 {
				i = hi
			}
			r, _ := bigWrap(i, v.w, v.signed)
			return r
		}
		fmt.Fprintf(&b, "const SatOut%s: [%d]%s = [%s]\n", up, n, v.name, joinf(n, func(i int) string { return v.lit(sat(math.Float64frombits(cb[i]))) }))
		fmt.Fprintf(&b, "const SatOut32%s: [%d]%s = [%s]\n", up, n, v.name, joinf(n, func(i int) string {
			return v.lit(sat(float64(float32(math.Float64frombits(cb[i])))))
		}))
		fmt.Fprintf(&b, `
VecSat%[1]s(): bool {
    for i in 0..%[2]d {
        if CastSat[%[3]s](f64.FromBits(SatIn[i])) != SatOut%[1]s[i] || CastSatF32[%[3]s](f32.FromBits(SatIn32[i])) != SatOut32%[1]s[i] {
            return false
        }
    }
    return true
}

const EvalSat%[1]s: bool = VecSat%[1]s()

test "CastSat to %[3]s, natively and in the evaluator" {
    Assert(EvalSat%[1]s)
    Assert(VecSat%[1]s())
}

`, up, n, v.name)
	}
	// MulWide, DivWide, AddCarry, SubBorrow.
	var xs, ys, zs []uint64
	we := []uint64{0, 1, 2, 1<<63 - 1, 1 << 63, ^uint64(0) - 1, ^uint64(0)}
	for _, x := range we {
		for _, y := range we {
			xs, ys, zs = append(xs, x), append(ys, y), append(zs, uint64(len(xs)%3))
		}
	}
	for i := 0; i < 24; i++ {
		xs, ys, zs = append(xs, rng.Uint64()), append(ys, rng.Uint64()), append(zs, rng.Uint64()&1)
	}
	n = len(xs)
	two64 := new(big.Int).Lsh(big.NewInt(1), 64)
	u := func(x uint64) *big.Int { return new(big.Int).SetUint64(x) }
	mh, ml, dq, dr, dh, dd, cs, cc, bd, bb := make([]uint64, n), make([]uint64, n), make([]uint64, n), make([]uint64, n),
		make([]uint64, n), make([]uint64, n), make([]uint64, n), make([]uint64, n), make([]uint64, n), make([]uint64, n)
	for i := range xs {
		p := new(big.Int).Mul(u(xs[i]), u(ys[i]))
		mh[i], ml[i] = new(big.Int).Rsh(p, 64).Uint64(), new(big.Int).Mod(p, two64).Uint64()
		// DivWide: a divisor above the high word, so the quotient fits.
		dd[i] = ys[i] | 1<<63
		dh[i] = xs[i] % dd[i]
		num := new(big.Int).Add(new(big.Int).Lsh(u(dh[i]), 64), u(ys[i]))
		dq[i], dr[i] = new(big.Int).Div(num, u(dd[i])).Uint64(), new(big.Int).Mod(num, u(dd[i])).Uint64()
		s := new(big.Int).Add(new(big.Int).Add(u(xs[i]), u(ys[i])), u(zs[i]))
		cs[i] = new(big.Int).Mod(s, two64).Uint64()
		if s.Cmp(two64) >= 0 {
			cc[i] = 1
		}
		d := new(big.Int).Sub(u(xs[i]), new(big.Int).Add(u(ys[i]), u(zs[i])))
		bd[i], bb[i] = new(big.Int).Mod(d, two64).Uint64(), 0
		if d.Sign() < 0 {
			bb[i] = 1
		}
	}
	arr := func(name string, a []uint64) {
		fmt.Fprintf(&b, "const %s: [%d]u64 = [%s]\n", name, n, joinf(n, func(i int) string { return fmt.Sprintf("0x%x", a[i]) }))
	}
	arr("WX", xs)
	arr("WY", ys)
	arr("WZ", zs)
	arr("MulHi", mh)
	arr("MulLo", ml)
	arr("DivHi", dh)
	arr("DivD", dd)
	arr("DivQ", dq)
	arr("DivR", dr)
	arr("CarryS", cs)
	arr("CarryC", cc)
	arr("BorrowD", bd)
	arr("BorrowB", bb)
	fmt.Fprintf(&b, `
VecWide(): bool {
    for i in 0..%d {
        m := MulWide(WX[i], WY[i])
        if m.hi != MulHi[i] || m.lo != MulLo[i] {
            return false
        }
        d := DivWide(DivHi[i], WY[i], DivD[i])
        if d.q != DivQ[i] || d.r != DivR[i] {
            return false
        }
        c := AddCarry(WX[i], WY[i], WZ[i])
        if c.sum != CarryS[i] || c.carry != CarryC[i] {
            return false
        }
        s := SubBorrow(WX[i], WY[i], WZ[i])
        if s.diff != BorrowD[i] || s.borrow != BorrowB[i] {
            return false
        }
    }
    return true
}

const EvalWide: bool = VecWide()

test "MulWide, DivWide, AddCarry and SubBorrow, natively and in the evaluator" {
    Assert(EvalWide)
    Assert(VecWide())
}
`, n)
	return b.String()
}

func TestNativeVectors(t *testing.T) {
	path := filepath.Join("..", "..", "std", "math", "tests_intrinsics_vec.mk")
	want := mathVectors()
	if *update {
		if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if strings.ReplaceAll(string(got), "\r\n", "\n") != want {
		t.Fatalf("%s is stale: go test ./internal/eval -run TestNativeVectors -update", path)
	}
}
