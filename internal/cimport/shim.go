// Why: a static inline C function, or a function-like macro with a
// declared signature, has no symbol to link against, so a binding cannot
// call it through extern alone.
//
// What: shimText, which writes one generated C file defining each such
// function under its C name, compiled in the same build graph; cDecl and
// join for C declarator spelling, shimmable and retWord.
//
// How: the headers are included with every static inline function renamed
// by a #define to __mk_inline_<name>, then each is defined under its C name
// as a call of the renamed one; a macro is first wrapped in a static inline
// function. So the binding's extern names its symbol as every other extern
// does.

package cimport

import (
	"fmt"
	"strconv"
	"strings"
)

// cDecl spells a C declaration of inner with type t (C11 6.7.6: pointers
// to functions and arrays parenthesised). It reports false for a type with
// no spelling outside its declaration (an unnamed tag).
func cDecl(t *ctype, inner string) (string, bool) {
	if t == nil {
		return "", false
	}
	switch t.kind {
	case tBuiltin:
		if t.name == "unsupported" {
			return "", false
		}
		return join(t.name, inner), true
	case tTypedef:
		return join(t.name, inner), true
	case tRecord, tEnum:
		if t.name == "" {
			return "", false
		}
		kw := "struct "
		if t.kind == tEnum {
			kw = "enum "
		} else if t.union {
			kw = "union "
		}
		return join(kw+t.name, inner), true
	case tPointer:
		if t.elem != nil && (t.elem.kind == tFunc || t.elem.kind == tArray) {
			return cDecl(t.elem, "(*"+inner+")")
		}
		return cDecl(t.elem, "*"+inner)
	case tArray:
		n := ""
		if t.n >= 0 {
			n = strconv.FormatInt(t.n, 10)
		}
		return cDecl(t.elem, inner+"["+n+"]")
	case tFunc:
		var ps []string
		for _, p := range t.params {
			s, ok := cDecl(p, "")
			if !ok {
				return "", false
			}
			ps = append(ps, s)
		}
		if t.variadic {
			ps = append(ps, "...")
		}
		if len(ps) == 0 {
			ps = []string{"void"}
		}
		return cDecl(t.ret, inner+"("+strings.Join(ps, ", ")+")")
	}
	return "", false
}

func join(base, inner string) string {
	if inner == "" {
		return base
	}
	return base + " " + inner
}

// shimmable reports whether the shim can spell f's result and parameters.
func shimmable(ret *ctype, ps []param) bool {
	if _, ok := cDecl(ret, "f"); !ok {
		return false
	}
	for _, p := range ps {
		if _, ok := cDecl(p.t, "x"); !ok {
			return false
		}
	}
	return true
}

// shimText is the shim file: the TU's defines and includes with every
// static inline function renamed, then one definition per function under
// its C name.
func shimText(imports []Import, fs []shimFunc) string {
	if len(fs) == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteString("/* Generated by mk: the static inline functions and declared macros of this package's C imports,\n")
	b.WriteString("   defined under their C names (see doc/reference.md). Never part of the repository. */\n")
	for _, f := range fs {
		if !f.macro {
			fmt.Fprintf(&b, "#define %s __mk_inline_%s\n", f.name, f.name)
		}
	}
	for _, im := range imports {
		for _, d := range im.Defines {
			name, val, _ := strings.Cut(d, "=")
			if val == "" && !strings.Contains(d, "=") {
				val = "1"
			}
			fmt.Fprintf(&b, "#define %s %s\n", name, val)
		}
		for _, h := range im.Headers {
			fmt.Fprintf(&b, "#include <%s>\n", h)
		}
	}
	for _, f := range fs {
		var params, args []string
		for i, p := range f.ps {
			n := "a" + strconv.Itoa(i)
			s, _ := cDecl(p.t, n)
			params = append(params, s)
			args = append(args, n)
		}
		if len(params) == 0 {
			params = []string{"void"}
		}
		target := "__mk_inline_" + f.name
		if f.macro {
			// The macro is wrapped first, then the name is freed for the
			// definition.
			head, _ := cDecl(f.ret, "__mk_macro_"+f.name+"("+strings.Join(params, ", ")+")")
			fmt.Fprintf(&b, "static inline %s { %s%s(%s); }\n", head, retWord(f.ret), f.name, strings.Join(args, ", "))
			fmt.Fprintf(&b, "#undef %s\n", f.name)
			target = "__mk_macro_" + f.name
		} else {
			fmt.Fprintf(&b, "#undef %s\n", f.name)
		}
		head, _ := cDecl(f.ret, f.name+"("+strings.Join(params, ", ")+")")
		fmt.Fprintf(&b, "%s { %s%s(%s); }\n", head, retWord(f.ret), target, strings.Join(args, ", "))
	}
	return b.String()
}

// retWord is "return " unless the function returns void.
func retWord(t *ctype) string {
	if t != nil && t.kind == tBuiltin && t.name == "void" {
		return ""
	}
	return "return "
}
