// Why: the compile-speed benchmarks need large Mk packages of a known size
// that read like plain code and are the same bytes on every machine.
//
// What: Generate, a deterministic plain-code Mk package of about kloc
// thousand lines, as unit files by path, with its pkg.mk manifest.
//
// How: one root module, main.mk, imports a module base and every module
// partNN; each partNN imports base. A part holds files of about 1,000 lines,
// so the work spreads over many modules that only base orders (the checker's
// parallel levels). Functions are plain code (int arithmetic, loops,
// branches, structs and methods, enums and match, an optional, a for loop)
// and call only functions declared before them, so there is no recursion.
// Nothing imports std or needs the test prelude. The text is a function of
// (seed, kloc) only: choices come from splitmix64, never math/rand or map
// order.

package corpus

import (
	"fmt"
	"slices"
	"strings"
)

// genFileLines is the size of one generated file, in lines.
const genFileLines = 1000

// genModuleKLOC is the size of one part module, in thousands of lines.
const genModuleKLOC = 4

// Generate returns a deterministic plain-code Mk package of about kloc
// thousand lines (at least one file of each kind), as files sorted by path:
// "base/base.mk", "main.mk", "part01/f01.mk", ..., "pkg.mk". A kloc below 1
// counts as 1.
func Generate(seed int64, kloc int) []UnitFile {
	if kloc < 1 {
		kloc = 1
	}
	g := &generator{rng: splitmix{state: uint64(seed)}}
	parts := max(1, kloc/genModuleKLOC)
	lines := kloc * genFileLines
	// base and main are small; the parts share the rest evenly.
	perPart := max(genFileLines/2, (lines-60-10*parts)/parts)
	var files []UnitFile
	files = append(files, UnitFile{Path: "base/base.mk", Text: g.base(seed, kloc)})
	names := make([]string, parts)
	for p := range parts {
		names[p] = fmt.Sprintf("part%02d", p+1)
		files = append(files, g.part(seed, kloc, names[p], perPart)...)
	}
	files = append(files, UnitFile{Path: "main.mk", Text: g.main(seed, kloc, names)})
	files = append(files, UnitFile{Path: "pkg.mk", Text: manifest})
	slices.SortFunc(files, func(a, b UnitFile) int { return strings.Compare(a.Path, b.Path) })
	return files
}

// manifest makes the files one package of many modules, on disk as in a
// corpus unit (a directory with no pkg.mk is a package of one module). A
// library: no bin, so no Main is needed. Every field is named, as manifest
// constructors require.
const manifest = `const Package = pkg.Package(
    name: "generated",
    bins: [],
    deps: [],
    c_sources: [],
    c_imports: [],
    asm_sources: [],
    targets: [],
    unsafe_modules: [],
    links: [],
)
`

// GenerateUnit is Generate's package as a corpus unit named name: verdict
// ok, no test prelude (the code needs none), judged by the one rule set.
func GenerateUnit(name string, seed int64, kloc int) *Unit {
	files := Generate(seed, kloc)
	// A directory unit's main.mk comes first (Unit's invariant).
	i := slices.IndexFunc(files, func(f UnitFile) bool { return f.Path == "main.mk" })
	files = append(append([]UnitFile{files[i]}, files[:i]...), files[i+1:]...)
	return &Unit{Key: name, Name: name, Verdict: VerdictOK, Files: files}
}

// splitmix is splitmix64 (Steele, Lea and Flood 2014): a fixed, portable
// sequence for a seed.
type splitmix struct{ state uint64 }

func (s *splitmix) next() uint64 {
	s.state += 0x9e3779b97f4a7c15
	z := s.state
	z = (z ^ (z >> 30)) * 0xbf58476d1ce4e5b9
	z = (z ^ (z >> 27)) * 0x94d049bb133111eb
	return z ^ (z >> 31)
}

// intn returns a number in [0, n), n > 0.
func (s *splitmix) intn(n int) int { return int(s.next() % uint64(n)) }

type generator struct {
	rng splitmix
}

// writer collects one file's text and counts its lines.
type writer struct {
	b     strings.Builder
	lines int
}

func (w *writer) line(format string, args ...any) {
	fmt.Fprintf(&w.b, format, args...)
	w.b.WriteByte('\n')
	w.lines++
}

func header(w *writer, seed int64, kloc int, what string) {
	w.line("// Generated by corpus.Generate(%d, %d): %s.", seed, kloc, what)
	w.line("")
}

// base is the module every part imports: one exported plain struct with
// methods and two exported functions.
func (g *generator) base(seed int64, kloc int) string {
	var w writer
	header(&w, seed, kloc, "the module every part imports")
	k := 3 + g.rng.intn(5)
	w.line("export struct Acc {")
	w.line("    export total: int")
	w.line("    export count: int")
	w.line("}")
	w.line("")
	w.line("export Acc.New(): Acc {")
	w.line("    return Acc(total: 0, count: 0)")
	w.line("}")
	w.line("")
	w.line("export Acc.Add(mut self, n: int) {")
	w.line("    self.total += n")
	w.line("    self.count += 1")
	w.line("}")
	w.line("")
	w.line("export Acc.Mean(&self): int {")
	w.line("    if self.count == 0 {")
	w.line("        return 0")
	w.line("    }")
	w.line("    return self.total / self.count")
	w.line("}")
	w.line("")
	w.line("export Mix(a: int, b: int): int {")
	w.line("    var h := a * %d + b", k)
	w.line("    if h < 0 {")
	w.line("        h = -h")
	w.line("    }")
	w.line("    return h %% 65521")
	w.line("}")
	w.line("")
	w.line("export Clamp(n: int, lo: int, hi: int): int {")
	w.line("    if n < lo {")
	w.line("        return lo")
	w.line("    }")
	w.line("    if n > hi {")
	w.line("        return hi")
	w.line("    }")
	w.line("    return n")
	w.line("}")
	return w.b.String()
}

// part is one module: files of about genFileLines lines each, about lines
// in all, ending with the exported Entry that main calls.
func (g *generator) part(seed int64, kloc int, name string, lines int) []UnitFile {
	var files []UnitFile
	var fns []string // the functions declared so far, in order
	n := 0           // the next declaration number
	left := lines
	for f := 1; ; f++ {
		var w writer
		header(&w, seed, kloc, "plain code of module "+name)
		w.line("import base")
		usedBase := false
		budget := min(left, genFileLines)
		for w.lines < budget-12 || !usedBase {
			n++
			fn, callsBase := g.decl(&w, n, fns)
			usedBase = usedBase || callsBase
			fns = append(fns, fn)
		}
		left -= w.lines
		// The module's last file, the one too little is left after, ends
		// with Entry; a file overshoots its budget by at most one group.
		last := left < 100
		if last {
			g.entry(&w, fns)
		}
		files = append(files, UnitFile{Path: fmt.Sprintf("%s/f%02d.mk", name, f), Text: w.b.String()})
		if last {
			return files
		}
	}
}

// callee returns a call of an earlier function of the module with the
// given arguments, or of base.Mix when there is none or by chance, and
// whether it is base's.
func (g *generator) callee(fns []string, a, b string) (string, bool) {
	if len(fns) == 0 || g.rng.intn(4) == 0 {
		return fmt.Sprintf("base.Mix(%s, %s)", a, b), true
	}
	// Prefer recent functions, so call chains stay local to a file.
	back := min(len(fns), 8)
	return fmt.Sprintf("%s(%s, %s)", fns[len(fns)-1-g.rng.intn(back)], a, b), false
}

// decl writes one declaration group ending in a function F<n>(a: int, b:
// int): int, and returns that function's name and whether it calls base.
func (g *generator) decl(w *writer, n int, fns []string) (string, bool) {
	fn := fmt.Sprintf("F%04d", n)
	c1, c2 := 1+g.rng.intn(9), 2+g.rng.intn(13)
	call, viaBase := g.callee(fns, "acc", fmt.Sprint(c1))
	w.line("")
	switch g.rng.intn(5) {
	case 0: // a loop with branches
		w.line("%s(a: int, b: int): int {", fn)
		w.line("    var acc := a")
		w.line("    for i in 0..b %% %d {", c2+4)
		w.line("        if i %% %d == 0 {", 2+c1%3)
		w.line("            acc += i * %d", c1)
		w.line("        } else if acc > %d {", 1000*c2)
		w.line("            acc -= b")
		w.line("        } else {")
		w.line("            acc += 1")
		w.line("        }")
		w.line("    }")
		w.line("    return acc + %s", call)
		w.line("}")
	case 1: // a plain struct and its methods
		p := fmt.Sprintf("P%04d", n)
		w.line("struct %s {", p)
		w.line("    x: int")
		w.line("    y: int")
		w.line("}")
		w.line("")
		w.line("%s.Sum(&self): int {", p)
		w.line("    return self.x + self.y * %d", c1)
		w.line("}")
		w.line("")
		w.line("%s.Scale(mut self, k: int) {", p)
		w.line("    self.x *= k")
		w.line("    self.y += k")
		w.line("}")
		w.line("")
		w.line("%s(a: int, b: int): int {", fn)
		w.line("    var p := %s(x: a, y: b)", p)
		w.line("    p.Scale(%d)", c1)
		w.line("    acc := p.Sum()")
		w.line("    if acc > %d {", 100*c2)
		w.line("        return acc - %s", call)
		w.line("    }")
		w.line("    return acc")
		w.line("}")
	case 2: // an enum and a match
		e := fmt.Sprintf("S%04d", n)
		w.line("enum %s {", e)
		w.line("    Dot")
		w.line("    Line(n: int)")
		w.line("    Box(w: int, h: int)")
		w.line("}")
		w.line("")
		w.line("%s.Of(a: int, b: int): %s {", e, e)
		w.line("    if a > b {")
		w.line("        return %s.Line(n: a - b)", e)
		w.line("    }")
		w.line("    if a < b {")
		w.line("        return %s.Box(w: a, h: b)", e)
		w.line("    }")
		w.line("    return %s.Dot", e)
		w.line("}")
		w.line("")
		w.line("%s(a: int, b: int): int {", fn)
		w.line("    acc := a + %d", c2)
		w.line("    match %s.Of(acc, b) {", e)
		w.line("        .Dot {")
		w.line("            return %d", c1)
		w.line("        }")
		w.line("        .Line(n) {")
		w.line("            return n + %s", call)
		w.line("        }")
		w.line("        .Box(w, h) {")
		w.line("            return w * %d + h", c1)
		w.line("        }")
		w.line("    }")
		w.line("}")
	case 3: // an optional and a `for x := ...` loop
		c := fmt.Sprintf("C%04d", n)
		w.line("struct %s {", c)
		w.line("    left: int")
		w.line("}")
		w.line("")
		w.line("%s.Next(mut self): ?int {", c)
		w.line("    if self.left <= 0 {")
		w.line("        return none")
		w.line("    }")
		w.line("    self.left -= 1")
		w.line("    return some(self.left)")
		w.line("}")
		w.line("")
		w.line("%s(a: int, b: int): int {", fn)
		w.line("    var acc := b")
		w.line("    var c := %s(left: a %% %d)", c, c2+2)
		w.line("    for n := c.Next() {")
		w.line("        acc += n * %d", c1)
		w.line("    }")
		w.line("    return acc + %s", call)
		w.line("}")
	default: // base's struct and an accumulation
		w.line("%s(a: int, b: int): int {", fn)
		w.line("    var s := base.Acc.New()")
		w.line("    for i in 0..%d {", c2)
		w.line("        s.Add(base.Clamp(a + i * b, %d, %d))", -100*c1, 100*c2)
		w.line("    }")
		w.line("    acc := s.Mean()")
		w.line("    return acc + %s", call)
		w.line("}")
		viaBase = true
	}
	return fn, viaBase
}

// entry is the module's exported Entry: a sum over its last functions.
func (g *generator) entry(w *writer, fns []string) {
	w.line("")
	w.line("export Entry(n: int): int {")
	w.line("    var t := 0")
	for _, fn := range fns[max(0, len(fns)-8):] {
		w.line("    t += %s(n, t %% %d)", fn, 3+g.rng.intn(11))
	}
	w.line("    return t")
	w.line("}")
}

// main is the root module: it imports base and every part and sums their
// Entry results.
func (g *generator) main(seed int64, kloc int, parts []string) string {
	var w writer
	header(&w, seed, kloc, "the root module")
	w.line("import base")
	for _, p := range parts {
		w.line("import %s", p)
	}
	w.line("")
	w.line("export Total(n: int): int {")
	w.line("    var t := base.Mix(n, %d)", 1+g.rng.intn(97))
	for _, p := range parts {
		w.line("    t += %s.Entry(n + t %% %d)", p, 2+g.rng.intn(7))
	}
	w.line("    return t")
	w.line("}")
	return w.b.String()
}
