// Why: a miscompile shows as a program whose result differs between the
// compile-time evaluator, a dev build and a release build. The oracle runs
// generated programs all three ways and compares.
//
// What: OracleBatch (many programs as one package), OracleNative and
// OracleBisect (the native half), OracleEval and OracleEvalSeam (the
// evaluator half), CompareOracle, DiffOwner, OracleMinimise and MiscompileOf.
// The quick set is TestOracle_Quick.
//
// How: up to OracleBatchMax programs are built as one package whose Main
// calls each program's Run on its seeds and prints one line per call. The
// evaluator half appends one const per seed that asserts equality. A trap
// bisects the batch; a difference is minimised and recorded with the side
// that owns it.

