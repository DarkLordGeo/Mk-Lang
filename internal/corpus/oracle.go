// OracleQuickBase is the quick set's base seed ("OracleQ1").
const OracleQuickBase uint64 = 0x4f7261636c655131

// OracleBatchMax is the most programs one batch package holds.
const OracleBatchMax = 128

// oracleManifest makes a batch one bin package whose root module is the
// batch directory; each program is a module p0000 to p0127 beside it.
const oracleManifest = `const Package = pkg.Package(
    name: "oracle",
    bins: [pkg.Bin(name: "oracle", root: ".", link_script: "", cpu: "", subsystem: "console")],
    deps: [],
    c_sources: [],
    c_imports: [],
    asm_sources: [],
    targets: [],
    unsafe_modules: [],
    links: [],
)
`

// oracleModule is program i's module name in a batch.
func oracleModule(i int) string { return fmt.Sprintf("p%04d", i) }

// i64Lit spells k's bits as an i64 literal expression.
func i64Lit(k uint64) string {
	v := int64(k)
	if v == -1<<63 {
		return "(-9223372036854775807 -% 1)"
	}
	return strconv.FormatInt(v, 10)
}

// OracleBatch is a package of len(progs) programs for the native half:
// module p0000 to p0127, each a program's text unchanged, and
// main.mk, whose Main calls each program's Run on each of its seeds
// (passing sys.arena and sys.io where the entry takes them) and prints one
// line "i j h" per call. Files are sorted by path.
func OracleBatch(progs []SoundProgram, seeds [][]uint64) []UnitFile {
	var m strings.Builder
	calls := 0
	for i := range progs {
		calls += len(seeds[i])
	}
	fmt.Fprintf(&m, "// Generated by corpus.OracleBatch: %d programs, %d calls.\n", len(progs), calls)
	for i := range progs {
		fmt.Fprintf(&m, "import %s\n", oracleModule(i))
	}
	m.WriteString("\nexport Main(sys: &System): WriteError!void {\n")
	m.WriteString("    var out := sys.Stdout()\n")
	m.WriteString("    var h: i64 = 0\n")
	for i, p := range progs {
		extra := ""
		for _, k := range p.Params[1:] {
			switch k {
			case "arena":
				extra += ", sys.arena"
			case "io":
				extra += ", sys.io"
			}
		}
		for j, k := range seeds[i] {
			fmt.Fprintf(&m, "    h = %s.Run(%s%s)\n", oracleModule(i), i64Lit(k), extra)
			fmt.Fprintf(&m, "    try Print(mut out, \"%d %d {h}\\n\", (h))\n", i, j)
		}
	}
	m.WriteString("}\n")
	files := []UnitFile{{Path: "main.mk", Text: m.String()}}
	for i, p := range progs {
		files = append(files, UnitFile{Path: oracleModule(i) + "/p.mk", Text: p.Text})
	}
	files = append(files, UnitFile{Path: "pkg.mk", Text: oracleManifest})
	return files
}

// writeUnitFiles writes files under dir, which it makes (and empties).
func writeUnitFiles(dir string, files []UnitFile) error {
	if err := os.RemoveAll(dir); err != nil {
		return err
	}
	for _, f := range files {
		p := filepath.Join(dir, filepath.FromSlash(f.Path))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(p, []byte(f.Text), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// OracleCacheDir is the one cache every oracle run shares:
// MK_CACHE when set, else mk-oracle-cache under the system's temporary
// directory. With the driver's default
// each fresh batch directory would get its own .mk-cache and check std and
// probe the toolchain cold.
func OracleCacheDir() string {
	if d := os.Getenv("MK_CACHE"); d != "" {
		return d
	}
	return filepath.Join(os.TempDir(), "mk-oracle-cache")
}

// OracleCacheBudget is the oracle cache's size budget, 4 GiB.
const OracleCacheBudget = 4 << 30

// NativeRun is one execution of a batch: the values by (program, seed),
// and where a call trapped.
type NativeRun struct {
	Vals [][]int64 // Vals[i][j]; valid where Got[i][j]
	Got  [][]bool
	Exit int
	// Trap is the first call with no line when the executable exited
	// non-zero (by construction no program traps, so it is a difference
	// against an evaluator that did not), or {-1, -1}. After OracleBisect it
	// is the first call Trapped names.
	Trap [2]int
	// Trapped, set by OracleBisect, names every call a batch of that call
	// alone showed trapping; nil before a bisection (Trap is then the one).
	Trapped [][]bool
	Stderr  string
	BuildMS int64
	RunMS   int64
}

// TrappedAt reports whether call (i, j) trapped.
func (n *NativeRun) TrappedAt(i, j int) bool {
	if n.Trapped != nil {
		return n.Trapped[i][j]
	}
	return n.Trap == [2]int{i, j}
}

// Ran reports whether call (i, j) was judged: it printed its line or it
// trapped. A call after a trap that no bisection reached was not run.
func (n *NativeRun) Ran(i, j int) bool { return n.Got[i][j] || n.TrappedAt(i, j) }

// OracleBisectBuilds bounds one bisection's builds (OracleBisect): beyond
// it the calls left are not run, and the record does not count them.
const OracleBisectBuilds = 64

// ocall is one call of a batch: program i on its seed j.
type ocall struct{ i, j int }

// OracleBisect completes run, the native execution of the batch of progs and
// seeds (at r's root under name) for target and profile, when it exited
// non-zero (by construction no program traps, so the batch is
// bisected to the calls that did). Main prints a call's line after the call
// returns, so every line printed is a value; only the calls with no line are
// rebuilt, as batches of their own under r's root. A batch of more than one
// call that exits non-zero and printed some lines (a panic report flushes
// the lines before it) runs its first call with no line alone, then the
// rest; one that printed none (a crash loses the buffered lines) is split
// in two half batches. A batch of one call that exits non-zero is that
// call's trap (Trapped). At most maxBuilds builds are made; calls still
// unresolved then are neither Got nor Trapped, so the comparison skips them
// (Ran) and the record does not count them. It returns the builds made.
func OracleBisect(r *Runner, name string, progs []SoundProgram, seeds [][]uint64, run *NativeRun, target, profile string, maxBuilds int) (int, error) {
	run.Trapped = make([][]bool, len(run.Got))
	for i := range run.Got {
		run.Trapped[i] = make([]bool, len(run.Got[i]))
	}
	var all []ocall
	for i := range run.Got {
		for j := range run.Got[i] {
			all = append(all, ocall{i, j})
		}
	}
	builds := 0
	var stack [][]ocall // batches still to run, the next on top
	// after takes the outcome of a run of calls that exited exit.
	after := func(calls []ocall, exit int) {
		if exit == 0 || len(calls) == 0 {
			return
		}
		if len(calls) == 1 {
			run.Trapped[calls[0].i][calls[0].j] = true
			return
		}
		var left []ocall
		for _, c := range calls {
			if !run.Got[c.i][c.j] {
				left = append(left, c)
			}
		}
		switch {
		case len(left) == 0:
			// Every call printed, and the executable still failed after
			// the last one: no call of it trapped.
		case len(left) < len(calls):
			stack = append(stack, left[1:], left[:1])
		default:
			h := len(calls) / 2
			stack = append(stack, calls[h:], calls[:h])
		}
	}
	after(all, run.Exit)
	for len(stack) > 0 {
		calls := stack[len(stack)-1]
		stack = stack[:len(stack)-1]
		if len(calls) == 0 {
			continue
		}
		if builds >= maxBuilds {
			break
		}
		builds++
		sub := fmt.Sprintf("%s-%s-%s-%d", name, profile, target, builds)
		exit, err := oracleSubBatch(r, sub, progs, seeds, calls, run, target, profile)
		if err != nil {
			return builds, err
		}
		after(calls, exit)
	}
	run.Trap = [2]int{-1, -1}
first:
	for i := range run.Trapped {
		for j := range run.Trapped[i] {
			if run.Trapped[i][j] {
				run.Trap = [2]int{i, j}
				break first
			}
		}
	}
	return builds, nil
}

// oracleSubBatch writes the calls of a bisection as the batch package sub
// under r's root, builds and runs it, and copies each line it printed into
// run at the call's place in the whole batch. It returns the exit status.
func oracleSubBatch(r *Runner, sub string, progs []SoundProgram, seeds [][]uint64, calls []ocall, run *NativeRun, target, profile string) (int, error) {
	var sp []SoundProgram
	var ss [][]uint64
	var back [][]ocall // back[i'][j'] is the call of the whole batch
	at := map[int]int{}
	for _, c := range calls {
		k, ok := at[c.i]
		if !ok {
			k = len(sp)
			at[c.i] = k
			sp = append(sp, progs[c.i])
			ss = append(ss, nil)
			back = append(back, nil)
		}
		ss[k] = append(ss[k], seeds[c.i][c.j])
		back[k] = append(back[k], c)
	}
	if err := writeUnitFiles(filepath.Join(r.root, sub), OracleBatch(sp, ss)); err != nil {
		return 0, err
	}
	nseeds := make([]int, len(sp))
	for k := range sp {
		nseeds[k] = len(ss[k])
	}
	nr, err := OracleNative(r, sub, nseeds, target, profile)
	if err != nil {
		return 0, err
	}
	for k := range back {
		for q, c := range back[k] {
			if nr.Got[k][q] {
				run.Vals[c.i][c.j], run.Got[c.i][c.j] = nr.Vals[k][q], true
			}
		}
	}
	return nr.Exit, nil
}

// OracleCompared counts what a batch's comparison judged: the calls whose
// dev and release executions both ran (Ran), and the programs every call of
// which did (the record counts only programs whose three values
// were compared).
func OracleCompared(seeds [][]uint64, dev, rel *NativeRun) (programs, calls int) {
	for i := range seeds {
		all := true
		for j := range seeds[i] {
			if dev.Ran(i, j) && rel.Ran(i, j) {
				calls++
			} else {
				all = false
			}
		}
		if all {
			programs++
		}
	}
	return programs, calls
}

// OracleNative builds the batch at root/name (written there by the caller)
// for target and profile ("dev", "release") through r, runs it with a 60 s
// hang guard and parses its lines. nseeds[i] is program i's seed
// count.
func OracleNative(r *Runner, name string, nseeds []int, target, profile string) (*NativeRun, error) {
	t0 := time.Now()
	if _, err := r.Build(name, target, profile); err != nil {
		return nil, err
	}
	out := &NativeRun{Trap: [2]int{-1, -1}, BuildMS: time.Since(t0).Milliseconds()}
	t1 := time.Now()
	res, err := r.Run(ProgramCase{Program: name, Timeout: 60 * time.Second}, target, profile)
	if err != nil {
		return nil, err
	}
	out.RunMS = time.Since(t1).Milliseconds()
	if res.TimedOut {
		return nil, fmt.Errorf("oracle batch %s (%s %s) did not finish within 60 s", name, target, profile)
	}
	out.Exit, out.Stderr = res.Exit, string(res.Stderr)
	out.Vals, out.Got = make([][]int64, len(nseeds)), make([][]bool, len(nseeds))
	for i, n := range nseeds {
		out.Vals[i], out.Got[i] = make([]int64, n), make([]bool, n)
	}
	sc := bufio.NewScanner(bytes.NewReader(res.Stdout))
	for sc.Scan() {
		var i, j int
		var h int64
		if _, err := fmt.Sscanf(sc.Text(), "%d %d %d", &i, &j, &h); err != nil || i < 0 || i >= len(nseeds) || j < 0 || j >= nseeds[i] {
			return nil, fmt.Errorf("oracle batch %s (%s %s): bad line %q", name, target, profile, sc.Text())
		}
		out.Vals[i][j], out.Got[i][j] = h, true
	}
	if out.Exit != 0 {
	find:
		for i := range out.Got {
			for j := range out.Got[i] {
				if !out.Got[i][j] {
					out.Trap = [2]int{i, j}
					break find
				}
			}
		}
	} else {
		for i := range out.Got {
			for j := range out.Got[i] {
				if !out.Got[i][j] {
					return nil, fmt.Errorf("oracle batch %s (%s %s) exited 0 without the line of program %d seed %d", name, target, profile, i, j)
				}
			}
		}
	}
	return out, nil
}

// oracleEqFn is the evaluator half's comparison: an assert that
// fails in a const evaluation exactly when the two values differ.
const oracleEqFn = `
OracleEq(a: i64, b: i64): bool {
    Assert(a == b)
    return true
}

OracleBit(v: i64, b: i64): bool {
    Assert(((v >> b) & 1) == 0)
    return true
}
`

// OracleEvalText is program p's text with the seam-free evaluator half
// appended: for each seed j, const OracleK<j>: bool =
// OracleEq(Run(k_j), want_j). lines[j] is that const's line.
func OracleEvalText(p SoundProgram, ks []uint64, want []int64) (text string, lines []int) {
	return oracleConsts(p, len(ks), func(j int) string {
		return fmt.Sprintf("const OracleK%d: bool = OracleEq(Run(%s), %s)", j, i64Lit(ks[j]), i64Lit(uint64(want[j])))
	})
}

// OracleBitsText reads Run(k) bit by bit: const OracleB<b>: bool =
// OracleBit(Run(k), b) fails exactly at the bits that are 1.
func OracleBitsText(p SoundProgram, k uint64) (text string, lines []int) {
	return oracleConsts(p, 64, func(b int) string {
		return fmt.Sprintf("const OracleB%d: bool = OracleBit(Run(%s), %d)", b, i64Lit(k), b)
	})
}

func oracleConsts(p SoundProgram, n int, line func(int) string) (string, []int) {
	var b strings.Builder
	b.WriteString(p.Text)
	b.WriteString(oracleEqFn)
	at := strings.Count(b.String(), "\n")
	b.WriteByte('\n')
	at++
	lines := make([]int, n)
	for j := range n {
		at++
		lines[j] = at
		b.WriteString(line(j))
		b.WriteByte('\n')
	}
	return b.String(), lines
}

// assertLines returns the lines of the unit's E0901 assert panics, and an
// error for any other diagnostic (the program was accepted, so the only
// diagnostics its consts can draw are their own evaluations').
func assertLines(out driver.UnitOutcome) (map[int]bool, error) {
	got := map[int]bool{}
	for _, e := range out.Report.Diags {
		d := e.Diag
		pos := out.Sources.Position(d.At.StartPos())
		f, ok := d.FactValue("panic")
		if d.Code != diag.E0901 || !ok || f.Kind != diag.FactText || f.Str != "assert" {
			return nil, fmt.Errorf("evaluator half: %s:%d:%d: %s %s", pos.Path, pos.Line, pos.Col, d.Code, d.Message)
		}
		got[int(pos.Line)] = true
	}
	return got, nil
}

// UnitChecker checks one unit's text under a fresh unit name; the oracle's
// evaluator half and the runner use it (CorpusSession.CheckUnit in a test,
// SoundCompiler.Check in a run).
type UnitChecker func(unit, text string) driver.UnitOutcome

// OracleEval is the seam-free evaluator half for one accepted program:
// same[j] says whether the evaluator's Run(k_j) equals want[j],
// and vals[j] is the evaluator's value (want[j] where same, else read bit
// by bit).
func OracleEval(check UnitChecker, unit string, p SoundProgram, ks []uint64, want []int64) (vals []int64, same []bool, err error) {
	text, lines := OracleEvalText(p, ks, want)
	failed, err := assertLines(check(unit+"/eq", text))
	if err != nil {
		return nil, nil, err
	}
	vals, same = make([]int64, len(ks)), make([]bool, len(ks))
	for j := range ks {
		same[j] = !failed[lines[j]]
		vals[j] = want[j]
		if same[j] {
			continue
		}
		bt, bl := OracleBitsText(p, ks[j])
		ones, err := assertLines(check(fmt.Sprintf("%s/bits%d", unit, j), bt))
		if err != nil {
			return nil, nil, err
		}
		var v uint64
		for b := range 64 {
			if ones[bl[b]] {
				v |= 1 << b
			}
		}
		vals[j] = int64(v)
	}
	return vals, same, nil
}

// OracleEvalSeam is the evaluator half through the soundness seam:
// p checked as unit, then Run(k) for each k of ks in the tagged mode (Seed
// k), whose value is the oracle's. For an oracle or core program, and any
// whose entry takes neither io nor a (oraclePlain), the same call is made in
// the plain mode too, which must give the same value (the tagged hooks may
// not change a value); the plain evaluator refuses Io and gives no arena, so
// a full program's io or a is the soundness host's alone.
// An oracle program is accepted, trap-free and fuel-free by construction, so
// a rejection, a violation, a Skipped run or an evaluator error is an error.
func OracleEvalSeam(s *driver.CorpusSession, unit string, p SoundProgram, ks []uint64) ([]int64, error) {
	out := s.CheckUnit(driver.UnitInput{Name: unit, Files: []driver.UnitFile{{Path: "sound.mk", Text: p.Text}}})
	if class, codes := classifySound(out.Report); class != "accepted" {
		return nil, fmt.Errorf("evaluator half: program %#x is %s %v", p.Seed, class, codes)
	}
	vals := make([]int64, len(ks))
	for j, k := range ks {
		tr := SoundRunOn(s, SoundRunSpec{Unit: unit, Fn: p.Entry, Args: []uint64{k}, Tag: &SoundTag{Seed: k}})
		switch {
		case len(tr.Violations) > 0:
			return nil, fmt.Errorf("evaluator half: program %#x k %#x: tagged run: %s (a soundness finding)", p.Seed, k, tr.Violations[0].Text)
		case tr.Skipped != "" || tr.ErrKind != "":
			return nil, fmt.Errorf("evaluator half: program %#x k %#x: tagged run skipped %q, err %s %s", p.Seed, k, tr.Skipped, tr.ErrKind, tr.ErrText)
		}
		if oraclePlain(p) {
			pr := SoundRunOn(s, SoundRunSpec{Unit: unit, Fn: p.Entry, Args: []uint64{k}})
			if pr.Skipped != "" || pr.ErrKind != "" || pr.Value != tr.Value {
				return nil, fmt.Errorf("evaluator half: program %#x k %#x: plain run %#x (skipped %q, err %s %s), tagged %#x", p.Seed, k, pr.Value, pr.Skipped, pr.ErrKind, pr.ErrText, tr.Value)
			}
		}
		vals[j] = int64(tr.Value)
	}
	return vals, nil
}

// oraclePlain reports whether the evaluator half also runs p in the plain
// mode (for oracle programs a plain run is made as well): an
// oracle or core program, or one whose entry takes only k, since the plain
// evaluator refuses an Io and has no arena to give.
func oraclePlain(p SoundProgram) bool {
	if p.Profile == ProfileOracle || p.Profile == ProfileCore {
		return true
	}
	return !slices.ContainsFunc(p.Params, func(k string) bool { return k == "io" || k == "arena" })
}

// OracleDiff is one difference between the three executions.
type OracleDiff struct {
	Program, SeedIndex int
	Seed, K            uint64
	Eval, Dev, Release int64
	Trapped            string // "dev", "release" or "" when every execution returned
	Presentation       string // "release differs; eval = dev", ...
	Owner              string // the area that owns it, by presentation
}

// DiffOwner names how a difference presents and who owns it (the code
// generator or the soundness checker), from which executions agree.
func DiffOwner(evalDev, evalRel, devRel bool) (presentation, owner string) {
	switch {
	case evalDev && !evalRel:
		return "release differs; eval = dev", "codegen"
	case evalRel && !evalDev:
		return "dev differs; eval = release", "codegen"
	case devRel && !evalDev:
		return "eval differs; dev = release", "borrow"
	case !evalDev && !evalRel && !devRel:
		return "all three differ", "codegen"
	}
	return "", ""
}

// OracleMinimise minimises difference d of program p: keep(t) is "t
// is accepted, and on seed d.K the differing execution still differs from
// the evaluator". Candidates are built in batches of 32, one build of the
// differing profile per batch, within 300 candidates or 20 minutes. root is
// a scratch directory; r builds under it.
func OracleMinimise(check UnitChecker, r *Runner, root, label string, p SoundProgram, d OracleDiff, target string) (string, MinStats) {
	prof := "dev"
	if d.Presentation == "release differs; eval = dev" {
		prof = "release"
	}
	n := 0
	keep := func(cands []string) []bool {
		ok := make([]bool, len(cands))
		var progs []SoundProgram
		var idx []int
		for i, c := range cands {
			n++
			out := check(fmt.Sprintf("oracle/%s/min/%d", label, n), c)
			if cl, _ := classifySound(out.Report); cl == "accepted" {
				q := p
				q.Text = c
				progs = append(progs, q)
				idx = append(idx, i)
			}
		}
		if len(progs) == 0 {
			return ok
		}
		seeds := make([][]uint64, len(progs))
		nseeds := make([]int, len(progs))
		for i := range progs {
			seeds[i], nseeds[i] = []uint64{d.K}, 1
		}
		name := fmt.Sprintf("min%d", n)
		if writeUnitFiles(filepath.Join(root, name), OracleBatch(progs, seeds)) != nil {
			return ok
		}
		nat, err := OracleNative(r, name, nseeds, target, prof)
		if err != nil {
			return ok
		}
		for j, q := range progs {
			got := nat.Vals[j][0]
			trapped := nat.TrappedAt(j, 0)
			if !nat.Got[j][0] && !trapped {
				continue
			}
			_, same, err := OracleEval(check, fmt.Sprintf("oracle/%s/min/%d/e%d", label, n, j), q, seeds[j], []int64{got})
			if err == nil && (!same[0] || trapped) {
				ok[idx[j]] = true
			}
		}
		return ok
	}
	return MinimiseBatch(p.Text, keep, 32, MinBudget{Candidates: 300, Time: 20 * time.Minute})
}

// MiscompileOf is the record of difference d, its text minimised.
func MiscompileOf(d OracleDiff, p SoundProgram, target, label, text string, st MinStats) *MiscompileRecord {
	return &MiscompileRecord{
		Oracle: d.Presentation, Owner: d.Owner, Target: target,
		Seeds:     fmt.Sprintf("k %#016x eval %#016x dev %#016x release %#016x", d.K, uint64(d.Eval), uint64(d.Dev), uint64(d.Release)),
		Gen:       fmt.Sprintf("%d %s seed %#016x", GenVersion, p.Profile, p.Seed),
		Found:     fmt.Sprintf("%s, run %s, build %x", time.Now().Format("2006-01-02"), label, driver.BuildID()),
		Minimised: fmt.Sprintf("%d lines to %d, %d candidates", st.FromLines, st.ToLines, st.Candidates),
		Text:      text,
	}
}

// CompareOracle compares the three executions of a batch and returns every
// difference, in program then seed order.
func CompareOracle(progs []SoundProgram, seeds [][]uint64, eval [][]int64, dev, rel *NativeRun) []OracleDiff {
	var out []OracleDiff
	for i := range progs {
		for j := range seeds[i] {
			d := OracleDiff{Program: i, SeedIndex: j, Seed: progs[i].Seed, K: seeds[i][j], Eval: eval[i][j]}
			dOK, rOK := dev.Got[i][j], rel.Got[i][j]
			d.Dev, d.Release = dev.Vals[i][j], rel.Vals[i][j]
			dTrap, rTrap := dev.TrappedAt(i, j), rel.TrappedAt(i, j)
			if !dev.Ran(i, j) || !rel.Ran(i, j) {
				continue // after a trap no bisection reached: not run
			}
			switch {
			case dTrap && rTrap:
				d.Trapped = "dev, release"
			case dTrap:
				d.Trapped = "dev"
			case rTrap:
				d.Trapped = "release"
			}
			ed := dOK && d.Eval == d.Dev
			er := rOK && d.Eval == d.Release
			dr := dOK == rOK && d.Dev == d.Release
			if ed && er {
				continue
			}
			d.Presentation, d.Owner = DiffOwner(ed, er, dr)
			out = append(out, d)
		}
	}
	return out
}
