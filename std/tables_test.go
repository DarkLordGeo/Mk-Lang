// Why: a transcription error or a Unicode version change must not reach Trim
// and Words unnoticed.
// What: TestTablesUpToDate and TestSpaceAtReadsTables for
// core/core_tables.mk, which today holds White_Space.
// How: genTables regenerates the file from the UCD's PropList.txt in
// $MK_EVIDENCE/ucd, the version std.text's tables come from, and compares it
// byte for byte; -update rewrites it. whiteSpaceRanges is Go's
// unicode.White_Space, which the tests that probe SpaceAt's edges read.

package std

import (
	"flag"
	"fmt"
	"os"
	"strings"
	"testing"
	"unicode"
	"unicode/utf8"
)

var update = flag.Bool("update", false, "rewrite the generated tables (core/core_tables.mk and the others) from their sources")

// tablesPath is the generated file, relative to std/.
const tablesPath = "core/core_tables.mk"

// scalarRange is one inclusive run of scalars.
type scalarRange struct{ lo, hi rune }

// appendScalar adds r to ascending runs, extending the last when r follows it.
func appendScalar(out []scalarRange, r rune) []scalarRange {
	if n := len(out); n > 0 && out[n-1].hi+1 == r {
		out[n-1].hi = r
		return out
	}
	return append(out, scalarRange{r, r})
}

// whiteSpaceRanges flattens unicode.White_Space into ascending inclusive
// runs of consecutive scalars (a stride other than 1 becomes single runs).
// It is Go's Unicode version (17.0.0), an oracle independent of the UCD
// parse; White_Space is the same set in 17.0.0 and 18.0.0, so when a later
// UCD changes it, TestSpaceAtMatchesUnicode fails on that version gap, not
// on SpaceAt.
func whiteSpaceRanges() []scalarRange {
	var out []scalarRange
	for _, r := range unicode.White_Space.R16 {
		for c := rune(r.Lo); c <= rune(r.Hi); c += rune(r.Stride) {
			out = appendScalar(out, c)
		}
	}
	for _, r := range unicode.White_Space.R32 {
		for c := rune(r.Lo); c <= rune(r.Hi); c += rune(r.Stride) {
			out = appendScalar(out, c)
		}
	}
	return out
}

// ucdWhiteSpace is White_Space from PropList.txt as ascending runs, and the
// file's UCD version.
func ucdWhiteSpace(dir string) ([]scalarRange, string, error) {
	in := make([]bool, unicode.MaxRune+1)
	v, err := ucdLines(dir, "PropList.txt", func(f []string) error {
		if len(f) != 2 || f[1] != "White_Space" {
			return nil
		}
		lo, hi, err := ucdRange(f[0])
		if err != nil {
			return err
		}
		for c := lo; c <= hi; c++ {
			in[c] = true
		}
		return nil
	})
	if err != nil {
		return nil, "", err
	}
	var out []scalarRange
	for c, ok := range in {
		if ok {
			out = appendScalar(out, rune(c))
		}
	}
	return out, v, nil
}

// genTables returns the text of core/core_tables.mk for the UCD in dir.
// SpaceAt (core_str.mk) reads AsciiSpace for bytes below 0x80 and
// WhiteSpace above.
func genTables(t *testing.T, dir string) string {
	t.Helper()
	ranges, version, err := ucdWhiteSpace(dir)
	if err != nil {
		t.Fatal(err)
	}
	if version == "" || len(ranges) == 0 {
		t.Fatalf("PropList.txt in %s: version %q, %d White_Space runs", dir, version, len(ranges))
	}
	var ascii uint64
	var wide []scalarRange
	for _, r := range ranges {
		for c := r.lo; c <= r.hi && c < utf8.RuneSelf; c++ {
			if c >= 64 {
				t.Fatalf("ASCII White_Space U+%04X is not below 64: AsciiSpace's 64-bit mask cannot hold it", c)
			}
			ascii |= 1 << uint(c)
		}
		if r.hi >= utf8.RuneSelf {
			lo := max(r.lo, utf8.RuneSelf)
			wide = append(wide, scalarRange{lo, r.hi})
		}
	}
	var b strings.Builder
	b.WriteString("// Code generated by std/tables_test.go from the UCD's PropList.txt. DO NOT EDIT.\n")
	b.WriteString("// The Unicode White_Space property that SpaceAt reads.\n")
	b.WriteString("// Regenerate with go test ./std -run TestTablesUpToDate -update (UCD in $MK_EVIDENCE/ucd).\n")
	fmt.Fprintf(&b, "// UCD version: %s\n\n", version)
	b.WriteString("// An inclusive run of scalar values.\n")
	b.WriteString("struct ScalarRange {\n    lo: u32\n    hi: u32\n}\n\n")
	b.WriteString("// Bit c is set when the ASCII byte c (below 64) is White_Space.\n")
	fmt.Fprintf(&b, "const AsciiSpace: u64 = 0x%X\n\n", ascii)
	b.WriteString("// White_Space at or above U+0080, ascending.\n")
	fmt.Fprintf(&b, "const WhiteSpace: [%d]ScalarRange = [\n", len(wide))
	for _, r := range wide {
		fmt.Fprintf(&b, "    ScalarRange(lo: 0x%04X, hi: 0x%04X),\n", r.lo, r.hi)
	}
	b.WriteString("]\n")
	return b.String()
}

// TestTablesUpToDate regenerates core/core_tables.mk from the UCD and
// compares it byte for byte; -update rewrites it.
func TestTablesUpToDate(t *testing.T) {
	needUCD(t)
	want := genTables(t, ucdDir())
	if *update {
		if err := os.WriteFile(tablesPath, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got := readText(t, tablesPath)
	if got != want {
		t.Errorf("%s is not what the UCD's PropList.txt gives; rerun go test ./std -run TestTablesUpToDate -update and read the diff\n--- got\n%s\n--- want\n%s", tablesPath, got, want)
	}
}

// TestSpaceAtReadsTables: SpaceAt in core_str.mk reads the generated
// tables and spells no White_Space scalar itself, so the table is the only
// transcription.
func TestSpaceAtReadsTables(t *testing.T) {
	src := readText(t, "core/core_str.mk")
	i := strings.Index(src, "\nexport SpaceAt(")
	if i < 0 {
		t.Fatal("core/core_str.mk declares no SpaceAt")
	}
	body := src[i:]
	if j := strings.Index(body[1:], "\n}\n"); j >= 0 {
		body = body[:j+3]
	}
	for _, name := range []string{"AsciiSpace", "WhiteSpace"} {
		if !strings.Contains(body, name) {
			t.Errorf("SpaceAt does not read %s", name)
		}
	}
	for _, lit := range []string{"0x20", "0x85", "0xA0", "0xE2", "0xE3", "0x3000", "0x2028"} {
		if strings.Contains(body, lit) {
			t.Errorf("SpaceAt spells %s itself; White_Space comes from %s only", lit, tablesPath)
		}
	}
}
