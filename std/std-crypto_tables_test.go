// Why: std/crypto/tables.mk holds edwards25519 constants and base-point
// multiples that must be exactly right and regenerable.
// What: a math/big affine model of edwards25519, TestSTDCRYPTO_GenerateTables
// and TestSTDCRYPTO_TablesMatchModel.
// How: the model computes d, 2d, sqrt(-1) and the signed-radix-16 comb;
// MK_CRYPTO_GEN=1 go test -run TestSTDCRYPTO_GenerateTables ./std rewrites it.

package std

import (
	"bytes"
	"fmt"
	"math/big"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// edPt is an affine point (x, y) of edwards25519, coordinates in [0, p).
type edPt struct{ x, y *big.Int }

func feMod(x *big.Int) *big.Int { return new(big.Int).Mod(x, feP) }

func feInv(x *big.Int) *big.Int { return new(big.Int).ModInverse(feMod(x), feP) }

// edD is -121665 / 121666 (RFC 8032 5.1).
var edD = feMod(new(big.Int).Mul(big.NewInt(-121665), feInv(big.NewInt(121666))))

// edL is the order of the base point, 2^252 + 27742317777372353535851937790883648493.
var edL, _ = new(big.Int).SetString("7237005577332262213973186563042994240857116359379907606001950938285454250989", 10)

// edAdd is the twisted Edwards addition with a = -1.
func edAdd(a, b edPt) edPt {
	x1x2 := new(big.Int).Mul(a.x, b.x)
	y1y2 := new(big.Int).Mul(a.y, b.y)
	dxy := feMod(new(big.Int).Mul(edD, new(big.Int).Mul(x1x2, y1y2)))
	xn := new(big.Int).Add(new(big.Int).Mul(a.x, b.y), new(big.Int).Mul(a.y, b.x))
	yn := new(big.Int).Add(y1y2, x1x2)
	one := big.NewInt(1)
	return edPt{
		feMod(new(big.Int).Mul(xn, feInv(new(big.Int).Add(one, dxy)))),
		feMod(new(big.Int).Mul(yn, feInv(new(big.Int).Sub(one, dxy)))),
	}
}

func edIdentity() edPt { return edPt{big.NewInt(0), big.NewInt(1)} }

// edMul is [k]P by double-and-add (variable time: a model).
func edMul(k *big.Int, p edPt) edPt {
	r := edIdentity()
	for i := k.BitLen() - 1; i >= 0; i-- {
		r = edAdd(r, r)
		if k.Bit(i) == 1 {
			r = edAdd(r, p)
		}
	}
	return r
}

// edBase is B: y = 4/5, x the even root.
func edBase() edPt {
	y := feMod(new(big.Int).Mul(big.NewInt(4), feInv(big.NewInt(5))))
	y2 := new(big.Int).Mul(y, y)
	u := feMod(new(big.Int).Sub(y2, big.NewInt(1)))
	v := feMod(new(big.Int).Add(new(big.Int).Mul(edD, y2), big.NewInt(1)))
	x := new(big.Int).ModSqrt(feMod(new(big.Int).Mul(u, feInv(v))), feP)
	if x.Bit(0) == 1 {
		x = feMod(new(big.Int).Neg(x))
	}
	return edPt{x, y}
}

// edEncode is RFC 8032 5.1.2's encoding.
func edEncode(p edPt) []byte {
	b := feBytes(p.y)
	b[31] |= byte(p.x.Bit(0) << 7)
	return b
}

// edDecode is Go's crypto/ed25519 decoding (y mod p, non-canonical y
// accepted, the sign bit chooses x, x = 0 with the sign bit accepted).
func edDecode(b []byte) (edPt, bool) {
	y := feMod(feLE(b))
	y2 := new(big.Int).Mul(y, y)
	u := feMod(new(big.Int).Sub(y2, big.NewInt(1)))
	v := feMod(new(big.Int).Add(new(big.Int).Mul(edD, y2), big.NewInt(1)))
	x := new(big.Int).ModSqrt(feMod(new(big.Int).Mul(u, feInv(v))), feP)
	if x == nil {
		return edPt{}, false
	}
	if x.Bit(0) != uint(b[31]>>7) {
		x = feMod(new(big.Int).Neg(x))
	}
	return edPt{x, y}, true
}

// feLimbs are the five 51-bit limbs of x's canonical value.
func feLimbs(x *big.Int) [5]uint64 {
	v := feMod(x)
	var l [5]uint64
	mask := new(big.Int).SetUint64(1<<51 - 1)
	for i := 0; i < 5; i++ {
		l[i] = new(big.Int).And(new(big.Int).Rsh(v, uint(51*i)), mask).Uint64()
	}
	return l
}

func feLiteral(x *big.Int) string {
	l := feLimbs(x)
	return fmt.Sprintf("Fe(l0: 0x%x, l1: 0x%x, l2: 0x%x, l3: 0x%x, l4: 0x%x)", l[0], l[1], l[2], l[3], l[4])
}

// affineLimbs are the 15 limbs of P's affine cached form: y + x, y - x,
// 2dxy.
func affineLimbs(p edPt) []uint64 {
	var out []uint64
	for _, f := range []*big.Int{
		new(big.Int).Add(p.y, p.x),
		new(big.Int).Sub(p.y, p.x),
		new(big.Int).Mul(new(big.Int).Mul(big.NewInt(2), edD), new(big.Int).Mul(p.x, p.y)),
	} {
		l := feLimbs(f)
		out = append(out, l[:]...)
	}
	return out
}

// cryptoTablesText is tables.mk as the model gives it.
func cryptoTablesText() string {
	var b strings.Builder
	b.WriteString(`// Code generated by std/std-crypto_tables_test.go from a math/big model of edwards25519. DO NOT EDIT.
// The constants D, D2 and SqrtM1 and the comb table BaseComb of the base point's multiples, which
// Ed25519 signing reads, as limb literals; every limb is canonical (below 2^51). Regenerate with
// MK_CRYPTO_GEN=1 go test ./std -run TestSTDCRYPTO_GenerateTables.

`)
	two := big.NewInt(2)
	sqrtM1 := new(big.Int).Exp(two, new(big.Int).Rsh(new(big.Int).Sub(feP, big.NewInt(1)), 2), feP)
	fmt.Fprintf(&b, "// D is d = -121665 / 121666 (RFC 8032 5.1).\nconst D: Fe = %s\n\n", feLiteral(edD))
	fmt.Fprintf(&b, "// D2 is 2d.\nconst D2: Fe = %s\n\n", feLiteral(new(big.Int).Mul(two, edD)))
	fmt.Fprintf(&b, "// SqrtM1 is 2^((p - 1) / 4), a square root of -1.\nconst SqrtM1: Fe = %s\n\n", feLiteral(sqrtM1))
	base := edBase()
	b.WriteString("// BaseComb holds (j + 1) 16^(2i) B for row i in 0..32 and j in 0..8, as\n// affine cached points: entry (8i + j) is the 15 limbs at 15 (8i + j), the\n// fields y + x, y - x and 2dxy in that order (ref10's ge_precomp base).\nconst BaseComb: [3840]u64 = [\n")
	row := base
	for i := 0; i < 32; i++ {
		p := row
		for j := 0; j < 8; j++ {
			writeLimbLine(&b, affineLimbs(p))
			p = edAdd(p, row)
		}
		// The next row's base is 256 times this one's.
		for k := 0; k < 8; k++ {
			row = edAdd(row, row)
		}
	}
	b.WriteString("]\n\n// BaseNaf holds (2i + 1) B for i in 0..64, the odd multiples a width-8\n// NAF digit names, laid out as BaseComb.\nconst BaseNaf: [960]u64 = [\n")
	b2 := edAdd(base, base)
	p := base
	for i := 0; i < 64; i++ {
		writeLimbLine(&b, affineLimbs(p))
		p = edAdd(p, b2)
	}
	b.WriteString("]\n")
	return b.String()
}

func writeLimbLine(b *strings.Builder, l []uint64) {
	b.WriteString("   ")
	for _, x := range l {
		fmt.Fprintf(b, " 0x%x,", x)
	}
	b.WriteString("\n")
}

// TestSTDCRYPTO_GenerateTables writes std/crypto/tables.mk, only when
// MK_CRYPTO_GEN=1.
func TestSTDCRYPTO_GenerateTables(t *testing.T) {
	if os.Getenv("MK_CRYPTO_GEN") != "1" {
		t.Skip("MK_CRYPTO_GEN=1 not set")
	}
	if err := os.WriteFile(filepath.Join("crypto", "tables.mk"), []byte(cryptoTablesText()), 0o644); err != nil {
		t.Fatal(err)
	}
}

// TestSTDCRYPTO_TablesMatchModel: tables.mk is exactly the model's text,
// and the model is right: B's encoding is RFC 8032's 0x5866...66, [L]B is
// the identity, sqrt(-1) squares to -1, and d satisfies d * 121666 = -121665.
func TestSTDCRYPTO_TablesMatchModel(t *testing.T) {
	got, err := os.ReadFile(filepath.Join("crypto", "tables.mk"))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(bytes.ReplaceAll(got, []byte("\r\n"), []byte("\n")), []byte(cryptoTablesText())) {
		t.Fatal("std/crypto/tables.mk is not the generator's output: run MK_CRYPTO_GEN=1 go test -run TestSTDCRYPTO_GenerateTables ./std")
	}
	base := edBase()
	if enc := fmt.Sprintf("%x", edEncode(base)); enc != "58"+strings.Repeat("66", 31) {
		t.Errorf("B encodes as %s", enc)
	}
	if id := edMul(edL, base); id.x.Sign() != 0 || id.y.Cmp(big.NewInt(1)) != 0 {
		t.Errorf("[L]B is not the identity")
	}
	s := new(big.Int).Exp(big.NewInt(2), new(big.Int).Rsh(new(big.Int).Sub(feP, big.NewInt(1)), 2), feP)
	if sq := feMod(new(big.Int).Mul(s, s)); sq.Cmp(new(big.Int).Sub(feP, big.NewInt(1))) != 0 {
		t.Errorf("sqrt(-1)^2 = %v", sq)
	}
	if c := feMod(new(big.Int).Mul(edD, big.NewInt(121666))); c.Cmp(feMod(big.NewInt(-121665))) != 0 {
		t.Errorf("d * 121666 = %v", c)
	}
}
