// Why: the runtime's own test blocks need to run in separate processes, with
// a watchdog and a chosen carrier count, seed and environment.
// What: TestRtSched_TestBlocks, _Stress, _Bench and _LinuxBlocks over every
// test block of std/rt/tests_*.mk and std/task/tests_*.mk, and the harness.
// How: in a copy of std each block becomes an exported function, and a
// generated module std.rtprobe calls the one a command-line index names. One
// executable holds every block; a block passes when its process exits 0 (a
// failed Assert is a panic, 101).

package std

