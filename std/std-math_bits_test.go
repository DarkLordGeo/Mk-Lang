// Why: std.math's integer operations must match Go's at every width.
// What: LeadingZeros, TrailingZeros, OnesCount, Rotate*, Reverse* against
// math/bits, Gcd against Euclid, CheckedPow and CheckedPowU64 against math/big.
// How: edge values and a seeded walk, natively at dev and release and in the
// evaluator (each line Main prints also comes from a const, which must agree).

package std

import (
	"fmt"
	"math/big"
	"math/bits"
	"strings"
	"testing"
)

// mathBitsInputs are the u64 inputs: zero, one, every power of two and its
// neighbours, all ones, alternating patterns and a seeded walk.
func mathBitsInputs() []uint64 {
	in := []uint64{0, 1, ^uint64(0), 0x5555555555555555, 0xAAAAAAAAAAAAAAAA, 0x0123456789ABCDEF, 0x8000000000000001}
	for i := 0; i < 64; i++ {
		p := uint64(1) << i
		in = append(in, p, p-1, p+1, ^p)
	}
	s := uint64(0x243F6A8885A308D3)
	for i := 0; i < 64; i++ {
		s = s*6364136223846793005 + 1442695040888963407
		in = append(in, s, s>>(s%64))
	}
	return in
}

// mathBitsShifts are the rotation amounts, negative and past the width
// included.
var mathBitsShifts = []int{0, 1, 3, 7, 8, 15, 16, 31, 32, 33, 63, 64, 65, 127, -1, -7, -8, -33, -64, -65, -1 << 62}

func mathBitsProgram(in []uint64) string {
	var b strings.Builder
	b.WriteString("// Generated by std/std-math_bits_test.go.\nimport std.math\n\n")
	fmt.Fprintf(&b, "const In: [%d]u64 = [", len(in))
	for i, w := range in {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "0x%X", w)
	}
	b.WriteString("]\n\n")
	fmt.Fprintf(&b, "const Shifts: [%d]int = [", len(mathBitsShifts))
	for i, k := range mathBitsShifts {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "%d", k)
	}
	b.WriteString("]\n\n")
	b.WriteString(`Mix(h: u64, w: u64): u64 {
    return (h ^ w) *% 0x100000001B3
}

Line(x: u64): u64 {
    var h: u64 = 0xCBF29CE484222325
    a := Trunc[u32](x)
    c := Trunc[u16](x)
    d := Trunc[u8](x)
    h = Mix(h, Cast[u64](math.LeadingZeros64(x) * 1000000 + math.LeadingZeros32(a) * 10000 + math.LeadingZeros16(c) * 100 + math.LeadingZeros8(d)))
    h = Mix(h, Cast[u64](math.TrailingZeros64(x) * 1000000 + math.TrailingZeros32(a) * 10000 + math.TrailingZeros16(c) * 100 + math.TrailingZeros8(d)))
    h = Mix(h, Cast[u64](math.OnesCount64(x) * 1000000 + math.OnesCount32(a) * 10000 + math.OnesCount16(c) * 100 + math.OnesCount8(d)))
    h = Mix(h, math.ReverseBytes64(x))
    h = Mix(h, u64(math.ReverseBytes32(a)))
    h = Mix(h, u64(math.ReverseBytes16(c)))
    h = Mix(h, math.ReverseBits64(x))
    h = Mix(h, u64(math.ReverseBits32(a)))
    h = Mix(h, u64(math.ReverseBits16(c)))
    h = Mix(h, u64(math.ReverseBits8(d)))
    for k in 0..Shifts.Len() {
        n := Shifts[k]
        h = Mix(h, math.RotateLeft64(x, n))
        h = Mix(h, math.RotateRight64(x, n))
        h = Mix(h, u64(math.RotateLeft32(a, n)))
        h = Mix(h, u64(math.RotateRight32(a, n)))
        h = Mix(h, u64(math.RotateLeft16(c, n)))
        h = Mix(h, u64(math.RotateRight16(c, n)))
        h = Mix(h, u64(math.RotateLeft8(d, n)))
        h = Mix(h, u64(math.RotateRight8(d, n)))
    }
    return h
}

GcdLine(i: int): u64 {
    var h: u64 = 0xCBF29CE484222325
    for j in 0..In.Len() {
        if (i + j) % 5 == 0 {
            h = Mix(h, math.Gcd(In[i], In[j]))
            h = Mix(h, math.Gcd(In[i] >> 40, In[j] >> 44))
        }
    }
    return h
}

PowLine(i: int): u64 {
    var h: u64 = 0xCBF29CE484222325
    x := Trunc[i64](In[i]) >> Trunc[int](In[i] % 64)
    for n in 0..70 {
        e := Trunc[u32](n)
        h = Mix(h, math.CheckedPowU64(In[i] >> Trunc[int](In[i] % 64), e) else { 0xDEAD })
        r := math.CheckedPow(x, e) else { 0x7EAD }
        h = Mix(h, Trunc[u64](r))
    }
    return h
}

All(): u64 {
    var h: u64 = 0
    // Every 32nd input, so the evaluator stays within its fuel.
    for i in 0..In.Len() {
        if i % 32 != 0 {
            continue
        }
        h = Mix(h, Line(In[i]))
        h = Mix(h, GcdLine(i))
        h = Mix(h, PowLine(i))
    }
    return h
}

const AllConst: u64 = All()

export Main(sys: &System): WriteError!void {
    for i in 0..In.Len() {
        try sys.Print("{a} {b} {c}\n", (a: Line(In[i]), b: GcdLine(i), c: PowLine(i)))
    }
    try sys.Print("{c} {r}\n", (c: AllConst, r: All()))
}
`)
	return b.String()
}

func fnvMix(h, w uint64) uint64 { return (h ^ w) * 0x100000001B3 }

func gcdModel(a, b uint64) uint64 {
	for b != 0 {
		a, b = b, a%b
	}
	return a
}

// mathBitsModel computes the program's lines in Go.
func mathBitsModel(in []uint64) string {
	var out strings.Builder
	var all uint64
	for i, x := range in {
		h := uint64(0xCBF29CE484222325)
		a, c, d := uint32(x), uint16(x), uint8(x)
		h = fnvMix(h, uint64(bits.LeadingZeros64(x)*1000000+bits.LeadingZeros32(a)*10000+bits.LeadingZeros16(c)*100+bits.LeadingZeros8(d)))
		h = fnvMix(h, uint64(bits.TrailingZeros64(x)*1000000+bits.TrailingZeros32(a)*10000+bits.TrailingZeros16(c)*100+bits.TrailingZeros8(d)))
		h = fnvMix(h, uint64(bits.OnesCount64(x)*1000000+bits.OnesCount32(a)*10000+bits.OnesCount16(c)*100+bits.OnesCount8(d)))
		h = fnvMix(h, bits.ReverseBytes64(x))
		h = fnvMix(h, uint64(bits.ReverseBytes32(a)))
		h = fnvMix(h, uint64(bits.ReverseBytes16(c)))
		h = fnvMix(h, bits.Reverse64(x))
		h = fnvMix(h, uint64(bits.Reverse32(a)))
		h = fnvMix(h, uint64(bits.Reverse16(c)))
		h = fnvMix(h, uint64(bits.Reverse8(d)))
		for _, n := range mathBitsShifts {
			// math/bits rotates by n mod the width, negative n to the right.
			h = fnvMix(h, bits.RotateLeft64(x, n%64))
			h = fnvMix(h, bits.RotateLeft64(x, -(n%64)))
			h = fnvMix(h, uint64(bits.RotateLeft32(a, n%32)))
			h = fnvMix(h, uint64(bits.RotateLeft32(a, -(n%32))))
			h = fnvMix(h, uint64(bits.RotateLeft16(c, n%16)))
			h = fnvMix(h, uint64(bits.RotateLeft16(c, -(n%16))))
			h = fnvMix(h, uint64(bits.RotateLeft8(d, n%8)))
			h = fnvMix(h, uint64(bits.RotateLeft8(d, -(n%8))))
		}
		g := uint64(0xCBF29CE484222325)
		for j := range in {
			if (i+j)%5 == 0 {
				g = fnvMix(g, gcdModel(in[i], in[j]))
				g = fnvMix(g, gcdModel(in[i]>>40, in[j]>>44))
			}
		}
		p := uint64(0xCBF29CE484222325)
		xs := int64(in[i]) >> (in[i] % 64)
		xu := in[i] >> (in[i] % 64)
		for n := 0; n < 70; n++ {
			ru := new(big.Int).Exp(new(big.Int).SetUint64(xu), big.NewInt(int64(n)), nil)
			if ru.IsUint64() {
				p = fnvMix(p, ru.Uint64())
			} else {
				p = fnvMix(p, 0xDEAD)
			}
			rs := new(big.Int).Exp(big.NewInt(xs), big.NewInt(int64(n)), nil)
			if rs.IsInt64() {
				p = fnvMix(p, uint64(rs.Int64()))
			} else {
				p = fnvMix(p, 0x7EAD)
			}
		}
		fmt.Fprintf(&out, "%d %d %d\n", h, g, p)
		if i%32 != 0 {
			continue
		}
		all = fnvMix(all, h)
		all = fnvMix(all, g)
		all = fnvMix(all, p)
	}
	fmt.Fprintf(&out, "%d %d\n", all, all)
	return out.String()
}

// TestSTDMATH_IntegerBitsMatchGo runs the program dev and release and
// compares every line with the Go model.
func TestSTDMATH_IntegerBitsMatchGo(t *testing.T) {
	t.Parallel()
	in := mathBitsInputs()
	src, want := mathBitsProgram(in), mathBitsModel(in)
	for _, prof := range [][]string{nil, {"--release"}} {
		exe := buildNative(t, nil, src, prof...)
		r := runNative(t, exe, "")
		if r.code != 0 || r.stdout != want {
			t.Fatalf("%v: exit %d\nstderr: %s\n%s", prof, r.code, r.stderr, coreNewDiff(r.stdout, want))
		}
	}
}
