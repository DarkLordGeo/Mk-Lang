// TestSTDMATH_ExhaustiveLinux reproduces the pinned digests on
// x86_64-linux (the recorded checksums agree on both targets). It
// runs with MK_LINUX=1 under the WSL lock (go test -p 1) and with
// MK_MATH_EXHAUSTIVE=verify or a list of functions. Each function is one
// wsl.exe client, run one after another: inside it, mathProcesses Linux
// processes split the blocks and write to Linux's own /tmp, never to the
// Windows drive, and the client prints the files when all exit.
func TestSTDMATH_ExhaustiveLinux(t *testing.T) {
	sel := os.Getenv("MK_MATH_EXHAUSTIVE")
	if sel == "" {
		t.Skip("MK_MATH_EXHAUSTIVE not set: the 2^32 run takes minutes per function")
	}
	needWSL(t)
	fns := mathExhaustiveFns
	if sel != "all" && sel != "verify" {
		fns = strings.Split(sel, ",")
	}
	exe := buildNative(t, nil, mathExhaustiveProgram(), "--target", "x86_64-linux", "--release")
	var report []string
	for _, fn := range fns {
		want, ok := mathExhaustive[fn]
		if !ok {
			t.Errorf("%s: no pinned digest", fn)
			continue
		}
		per := mathBlocks / mathProcesses
		var sh strings.Builder
		sh.WriteString(`d=$(mktemp -d /tmp/mkmath.XXXXXX) && [ -n "$d" ] || exit 9; `)
		for p := 0; p < mathProcesses; p++ {
			fmt.Fprintf(&sh, `timeout -k 5 240 ./%s %s %d %d > "$d/%d" & `, filepath.Base(exe), fn, p*per, (p+1)*per, p)
		}
		sh.WriteString(`wait; cat "$d"/[0-9]*; rm -rf -- "$d"`)
		start := time.Now()
		stdout, stderr, code := runWSLShell(t, filepath.Dir(exe), sh.String())
		if code != 0 {
			t.Errorf("%s: exit %d\n%s", fn, code, stderr)
			continue
		}
		sums := make([]uint64, mathBlocks)
		seen := 0
		for _, line := range strings.Split(strings.TrimSpace(stdout), "\n") {
			fs := strings.Fields(line)
			if len(fs) != 2 {
				continue
			}
			bk, err1 := strconv.Atoi(fs[0])
			h, err2 := strconv.ParseUint(fs[1], 10, 64)
			if err1 != nil || err2 != nil || bk < 0 || bk >= mathBlocks {
				continue
			}
			sums[bk] = h
			seen++
		}
		if seen != mathBlocks {
			t.Errorf("%s: %d of %d block checksums came back\n%s", fn, seen, mathBlocks, stderr)
			continue
		}
		digest := fmt.Sprintf("%016x", mathDigest(sums))
		if digest != want.digest {
			t.Errorf("%s: x86_64-linux digest %s, pinned %s (x86_64-windows)", fn, digest, want.digest)
		}
		report = append(report, fmt.Sprintf("%s: digest %s (%s)", fn, digest, time.Since(start).Round(time.Second)))
	}
	t.Logf("exhaustive f32 run on x86_64-linux:\n  %s", strings.Join(report, "\n  "))
}

// runWSLShell runs the sh command line cmd in dir through one wsl.exe
// client, bounded by 5 minutes.
func runWSLShell(t *testing.T, dir, cmd string) (string, string, int) {
	t.Helper()
	wslGuard()
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer cancel()
	// --exec: no default shell in between, so cmd reaches sh -c unexpanded.
	c := exec.CommandContext(ctx, "wsl.exe", "--cd", wslPath(dir), "--exec", "sh", "-c", cmd)
	c.WaitDelay = 10 * time.Second
	var o, e bytes.Buffer
	c.Stdout, c.Stderr = &o, &e
	err := c.Run()
	status := 0
	if ee, ok := err.(*exec.ExitError); ok {
		status = ee.ExitCode()
	} else if err != nil {
		t.Fatalf("wsl.exe sh -c %q: %v", cmd, err)
	}
	return o.String(), e.String(), status
}
