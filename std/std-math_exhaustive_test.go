// Why: every one-argument f32 function of std.math must be correctly rounded
// on all 2^32 inputs, which only an exhaustive run proves.
// What: the exhaustive run, its pinned digests (mathExhaustive) and a Linux leg.
// How: Mk and the Go oracle (mathCR32) fold each 2^20-input block into an
// FNV-1a checksum; differing blocks are dumped (see TestSTDMATH_Exhaustive).

