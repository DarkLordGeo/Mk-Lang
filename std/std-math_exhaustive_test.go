// mathExhaustiveFns are the one-argument f32 functions, by f64 name: the
// 27 that return one f32, then the four whose result is folded as a key
// (mathKeyFns).
var mathExhaustiveFns = []string{"Sqrt", "Floor", "Ceil", "RoundToZero", "Round", "RoundEven", "Fract",
	"Exp", "Exp2", "Expm1", "Log", "Log2", "Log10", "Log1p", "Sin", "Cos", "Tan", "Asin", "Acos", "Atan",
	"Sinh", "Cosh", "Tanh", "Asinh", "Acosh", "Atanh", "Cbrt",
	"FrExp", "IsNan", "IsInf", "IsFinite"}

// mathKeyFns are the one-argument f32 functions folded as a u64 key, not
// one f32 (the run covers every one-argument f32 function):
// FrExpF32's frac bits with exp + 512 above them, and each classifier as 0
// or 1. The Mk side's KeyFrExp, KeyIsNan, KeyIsInf and KeyIsFinite fold
// the same key.
var mathKeyFns = map[string]func(xb uint32) uint64{
	"FrExp": func(xb uint32) uint64 {
		x := float64(math.Float32frombits(xb))
		switch {
		case math.IsNaN(x):
			return 0x7FC00000 | 512<<32 // NanF32, exp 0
		case x == 0 || math.IsInf(x, 0):
			return uint64(xb) | 512<<32
		}
		frac, exp := math.Frexp(x)
		return uint64(math.Float32bits(float32(frac))) | uint64(exp+512)<<32
	},
	"IsNan":    func(xb uint32) uint64 { return mathBool(xb&0x7FFFFFFF > 0x7F800000) },
	"IsInf":    func(xb uint32) uint64 { return mathBool(xb&0x7FFFFFFF == 0x7F800000) },
	"IsFinite": func(xb uint32) uint64 { return mathBool(xb&0x7F800000 != 0x7F800000) },
}

func mathBool(b bool) uint64 {
	if b {
		return 1
	}
	return 0
}

// mathKey32 is the oracle's folded value for one input: the correctly
// rounded bits, or mathKeyFns' key.
func mathKey32(fn string, xb uint32) uint64 {
	if k, ok := mathKeyFns[fn]; ok {
		return k(xb)
	}
	return uint64(mathCR32(fn, xb))
}

const (
	mathBlocks    = 4096 // blocks of 2^20 inputs
	mathProcesses = 8
)

func mathExhaustiveProgram() string {
	var b strings.Builder
	b.WriteString(`// Generated by std/std-math_exhaustive_test.go.
import std.math

// Block folds f's result bits over the 2^20 inputs of block b, or prints
// each when dump is set.
Block(out: mut Writer, f: fn(x: f32): f32, b: int, dump: bool): WriteError!u64 {
    var h: u64 = 0xCBF29CE484222325
    base := b * 1048576
    for i in 0..1048576 {
        r := f(f32.FromBits(Trunc[u32](base + i))).Bits()
        h = (h ^ u64(r)) *% 0x100000001B3
        if dump {
            try Print(out, "{r}\n", (r))
        }
    }
    return h
}

Run(out: mut Writer, f: fn(x: f32): f32, first: int, last: int, dump: bool): WriteError!void {
    for b in first..last {
        h := try Block(out, f, b, dump)
        if !dump {
            try Print(out, "{b} {h}\n", (b, h))
        }
    }
}

// BlockKey is Block for a function folded as a u64 key.
BlockKey(out: mut Writer, f: fn(x: f32): u64, b: int, dump: bool): WriteError!u64 {
    var h: u64 = 0xCBF29CE484222325
    base := b * 1048576
    for i in 0..1048576 {
        r := f(f32.FromBits(Trunc[u32](base + i)))
        h = (h ^ r) *% 0x100000001B3
        if dump {
            try Print(out, "{r}\n", (r))
        }
    }
    return h
}

RunKey(out: mut Writer, f: fn(x: f32): u64, first: int, last: int, dump: bool): WriteError!void {
    for b in first..last {
        h := try BlockKey(out, f, b, dump)
        if !dump {
            try Print(out, "{b} {h}\n", (b, h))
        }
    }
}

KeyFrExp(x: f32): u64 {
    r := math.FrExpF32(x)
    return u64(r.frac.Bits()) | Cast[u64](r.exp + 512) << 32
}

KeyIsNan(x: f32): u64 {
    return if math.IsNanF32(x) { 1 } else { 0 }
}

KeyIsInf(x: f32): u64 {
    return if math.IsInfF32(x) { 1 } else { 0 }
}

KeyIsFinite(x: f32): u64 {
    return if math.IsFiniteF32(x) { 1 } else { 0 }
}

export Main(sys: &System): WriteError|ParseError!void {
    var out := sys.Stdout()
    name := sys.args[1]
    first := Trunc[int](try sys.args[2].ParseInt())
    last := Trunc[int](try sys.args[3].ParseInt())
    dump := sys.args.Len() > 4
`)
	for _, f := range mathExhaustiveFns {
		if _, ok := mathKeyFns[f]; ok {
			fmt.Fprintf(&b, "    if name == %q {\n        try RunKey(mut out, Key%s, first, last, dump)\n    }\n", f, f)
			continue
		}
		fmt.Fprintf(&b, "    if name == %q {\n        try Run(mut out, math.%sF32, first, last, dump)\n    }\n", f, f)
	}
	b.WriteString("}\n")
	return b.String()
}

// mathRunMk runs exe with args, without the test's runTimeout: a range of
// 512 blocks takes up to a few minutes.
func mathRunMk(exe string, args ...string) (string, error) {
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Minute)
	defer cancel()
	cmd := exec.CommandContext(ctx, exe, args...)
	var out, errb bytes.Buffer
	cmd.Stdout, cmd.Stderr = &out, &errb
	if err := cmd.Run(); err != nil {
		return "", fmt.Errorf("%v: %v\n%s", args, err, errb.String())
	}
	return out.String(), nil
}

// mathMkBlocks runs fn's 4,096 blocks in mathProcesses processes.
func mathMkBlocks(exe, fn string) ([]uint64, error) {
	sums := make([]uint64, mathBlocks)
	var wg sync.WaitGroup
	errs := make([]error, mathProcesses)
	per := mathBlocks / mathProcesses
	for p := 0; p < mathProcesses; p++ {
		wg.Add(1)
		go func(p int) {
			defer wg.Done()
			out, err := mathRunMk(exe, fn, strconv.Itoa(p*per), strconv.Itoa((p+1)*per))
			if err != nil {
				errs[p] = err
				return
			}
			for _, line := range strings.Split(strings.TrimSpace(out), "\n") {
				fs := strings.Fields(line)
				bk, _ := strconv.Atoi(fs[0])
				h, _ := strconv.ParseUint(fs[1], 10, 64)
				sums[bk] = h
			}
		}(p)
	}
	wg.Wait()
	for _, err := range errs {
		if err != nil {
			return nil, err
		}
	}
	return sums, nil
}

// mathGoBlocks folds the oracle's results the same way.
func mathGoBlocks(fn string) []uint64 {
	sums := make([]uint64, mathBlocks)
	var wg sync.WaitGroup
	next := make(chan int, mathBlocks)
	for b := 0; b < mathBlocks; b++ {
		next <- b
	}
	close(next)
	for w := 0; w < mathProcesses; w++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for b := range next {
				h := uint64(0xCBF29CE484222325)
				for i := 0; i < 1<<20; i++ {
					h = (h ^ mathKey32(fn, uint32(b<<20+i))) * 0x100000001B3
				}
				sums[b] = h
			}
		}()
	}
	wg.Wait()
	return sums
}

func mathDigest(sums []uint64) uint64 {
	h := uint64(0xCBF29CE484222325)
	for _, s := range sums {
		h = (h ^ s) * 0x100000001B3
	}
	return h
}

// TestSTDMATH_Exhaustive is the run: every one-argument f32 function over
// all 2^32 inputs. A Mk program folds the result bits of each block of 2^20
// inputs into one FNV-1a checksum, eight processes over disjoint block
// ranges; the Go oracle (mathCR32: Go's f64 value, recomputed at 512 bits
// within 2^-20 of an f32 ulp of a rounding boundary, checked against
// Mk-evidence/math first) folds the correctly rounded bits the same way. A
// block whose checksums differ is dumped input by input and every
// misrounded input is reported with its distance in ulps. FrExpF32 and the
// three classifiers, whose result is not one f32, fold a u64 key instead
// (mathKeyFns), and any difference there is wrong. The run takes minutes
// per function, so it runs only with MK_MATH_EXHAUSTIVE set: "all", or a
// comma-separated list of function names (the f64 names: Exp for ExpF32).
// Each function's digest (the hash of its 4,096 block checksums) is logged
// and pinned in mathExhaustive; with MK_MATH_EXHAUSTIVE=verify only the Mk
// side runs and must reproduce the pins, which is what the gate compares.
func TestSTDMATH_Exhaustive(t *testing.T) {
	sel := os.Getenv("MK_MATH_EXHAUSTIVE")
	if sel == "" {
		t.Skip("MK_MATH_EXHAUSTIVE not set: the 2^32 run takes minutes per function")
	}
	verify := sel == "verify"
	fns := mathExhaustiveFns
	if sel != "all" && !verify {
		fns = strings.Split(sel, ",")
	}
	exe := buildNative(t, nil, mathExhaustiveProgram(), "--release")
	var report []string
	for _, fn := range fns {
		if !slices.Contains(mathExhaustiveFns, fn) {
			t.Errorf("%s: not a one-argument f32 function of std.math", fn)
			continue
		}
		start := time.Now()
		mk, err := mathMkBlocks(exe, fn)
		if err != nil {
			t.Errorf("%s: %v", fn, err)
			continue
		}
		mkTime := time.Since(start)
		digest := fmt.Sprintf("%016x", mathDigest(mk))
		if verify {
			if want, ok := mathExhaustive[fn]; ok && want.digest != digest {
				t.Errorf("%s: digest %s, pinned %s: the function's results changed", fn, digest, want.digest)
			}
			report = append(report, fmt.Sprintf("%s: digest %s (Mk %s)", fn, digest, mkTime.Round(time.Second)))
			continue
		}
		start = time.Now()
		gold := mathGoBlocks(fn)
		goTime := time.Since(start)
		var badBlocks []int
		for b := range mk {
			if mk[b] != gold[b] {
				badBlocks = append(badBlocks, b)
			}
		}
		// Bisect: dump each differing block and compare input by input.
		misrounded, oracleFixed := 0, 0
		var worst uint64
		var examples []string
		for _, b := range badBlocks {
			out, err := mathRunMk(exe, fn, strconv.Itoa(b), strconv.Itoa(b+1), "dump")
			if err != nil {
				t.Errorf("%s: dump of block %d: %v", fn, b, err)
				continue
			}
			lines := strings.Split(strings.TrimSpace(out), "\n")
			for i, line := range lines {
				xb := uint32(b<<20 + i)
				if key, ok := mathKeyFns[fn]; ok {
					// Exact: any difference is wrong.
					got, _ := strconv.ParseUint(line, 10, 64)
					if want := key(xb); got != want {
						misrounded++
						if len(examples) < 32 {
							examples = append(examples, fmt.Sprintf("%s(%08x): key %x, want %x", fn, xb, got, want))
						}
					}
					continue
				}
				got, _ := strconv.ParseUint(line, 10, 32)
				want := mathCR32(fn, xb)
				if uint32(got) == want {
					continue
				}
				// Settle the disagreement at 512 bits alone: Go's f64 Sin, Cos
				// and Tan lose accuracy at large arguments, so the oracle's
				// first estimate can be the wrong side.
				if y, _ := mathBigEval(fn, float64(math.Float32frombits(xb))).Float32(); math.Float32bits(y) != want {
					oracleFixed++
					want = math.Float32bits(y)
					if uint32(got) == want {
						continue
					}
				}
				misrounded++
				d := mathDistance(got, uint64(want), true)
				if d > worst {
					worst = d
				}
				if len(examples) < 32 {
					examples = append(examples, fmt.Sprintf("%s(%08x = %g): got %08x, correctly rounded %08x (%d ulp)",
						fn, xb, math.Float32frombits(xb), got, want, d))
				}
			}
		}
		line := fmt.Sprintf("%s: %d misrounded of 2^32, largest distance %d ulp, digest %s (Mk %s, oracle %s; %d oracle estimates corrected at 512 bits)",
			fn, misrounded, worst, digest, mkTime.Round(time.Second), goTime.Round(time.Second), oracleFixed)
		report = append(report, line)
		if len(examples) > 0 {
			t.Logf("%s\n  %s", line, strings.Join(examples, "\n  "))
		}
		if want, ok := mathExhaustive[fn]; ok && (want.digest != digest || want.misrounded != misrounded) {
			t.Errorf("%s: digest %s and %d misrounded, pinned %s and %d", fn, digest, misrounded, want.digest, want.misrounded)
		}
	}
	t.Logf("exhaustive f32 run:\n  %s", strings.Join(report, "\n  "))
}

