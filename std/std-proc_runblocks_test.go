// Why: std.proc's test blocks start, supervise and kill processes, so each
// needs a process of its own, which mk test cannot give it.
// What: TestProc_RunBlocks, TestProc_RunLinuxBlocks, TestProc_RunBlockNames and the
// runner's helpers (proc2Rewrite, proc2CopyStd, proc2Build).
// How: rewrites each block of std/proc/tests_run.mk into an exported function
// of a std copy; one executable runs block i in its own process.
//
// Each block runs under a watchdog, at dev and release, with MK_CARRIERS 1
// and 8, and passes when its process exits 0. A block's children are this
// same executable (Run's modes, Supervise's re-exec), so they need no other
// program.
//
// MK_PROC2_BASE, when set, is a directory holding the std to copy instead of
// the tree's, for runs while other std files are mid-edit.
//
// TestProc_RunLinuxBlocks starts wsl.exe, so it runs only with MK_LINUX=1,
// under tools/wsl-lock.ps1, with go test -p 1.

package std

import (
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"runtime"
	"slices"
	"strings"
	"testing"
)

// proc2Block is one rewritten block.
type proc2Block struct {
	name string
	fn   string
}

var proc2Header = regexp.MustCompile(`^test "([^"]*)"\s*(\(sys: &System\))?\s*\{\s*$`)

// proc2Files are the files whose blocks this runner runs.
var proc2Files = []string{"proc/tests_run.mk", "proc/tests_supervise.mk"}

// proc2Rewrite returns the fixtures and the blocks in file order.
func proc2Rewrite(t *testing.T, base string) (map[string]string, []proc2Block) {
	t.Helper()
	fixtures := map[string]string{}
	var blocks []proc2Block
	for _, f := range proc2Files {
		b, err := os.ReadFile(filepath.Join(base, filepath.FromSlash(f)))
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			t.Fatal(err)
		}
		lines := strings.Split(strings.ReplaceAll(string(b), "\r\n", "\n"), "\n")
		for i, line := range lines {
			m := proc2Header.FindStringSubmatch(line)
			if m == nil {
				continue
			}
			fn := fmt.Sprintf("ZzP2Test%d", len(blocks))
			if m[2] == "" {
				lines[i] = "export " + fn + "(sys: &System) {"
			} else {
				lines[i] = "export " + fn + "(sys: &System) {"
			}
			blocks = append(blocks, proc2Block{name: m[1], fn: fn})
		}
		fixtures[f] = strings.Join(lines, "\n")
	}
	var p strings.Builder
	p.WriteString("// Generated by std/std-proc_runblocks_test.go.\n\n")
	p.WriteString("export ZzP2Run(sys: &System, i: int): bool {\n")
	for i, b := range blocks {
		fmt.Fprintf(&p, "    if i == %d {\n        %s(sys)\n        return true\n    }\n", i, b.fn)
	}
	p.WriteString("    return false\n}\n")
	fixtures["proc/zzp2probe.mk"] = p.String()
	return fixtures, blocks
}

// proc2Main runs the block whose index is the first argument.
const proc2Main = `import std.proc

export Main(sys: &System): int {
    if sys.args.Len() < 2 {
        return 2
    }
    var n := 0
    for b in sys.args[1].AsBytes() {
        n = n * 10 + int(b) - 48
    }
    if !proc.ZzP2Run(sys, n) {
        return 2
    }
    return 0
}
`

// proc2Base is the directory whose std is copied: MK_PROC2_BASE/std, or
// the tree's std (the test's working directory).
func proc2Base() string {
	if b := os.Getenv("MK_PROC2_BASE"); b != "" {
		return filepath.Join(b, "std")
	}
	return "."
}

// proc2CopyStd copies base's .mk and .def files under root/std, then the
// fixtures over them.
func proc2CopyStd(t *testing.T, root, base string, fixtures map[string]string) string {
	t.Helper()
	stdDir := filepath.Join(root, "std")
	err := fs.WalkDir(os.DirFS(base), ".", func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !(strings.HasSuffix(p, ".mk") || strings.HasSuffix(p, ".def")) {
			return err
		}
		b, err := os.ReadFile(filepath.Join(base, filepath.FromSlash(p)))
		if err != nil {
			return err
		}
		dst := filepath.Join(stdDir, filepath.FromSlash(p))
		if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
			return err
		}
		return os.WriteFile(dst, b, 0o644)
	})
	if err != nil {
		t.Fatal(err)
	}
	for p, text := range fixtures {
		dst := filepath.Join(stdDir, filepath.FromSlash(p))
		if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(dst, []byte(text), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return stdDir
}

// proc2Build builds the runner over a copy of the base std with the
// std/proc files of this tree over it.
func proc2Build(t *testing.T, linux bool, flags ...string) (string, []proc2Block) {
	t.Helper()
	base := proc2Base()
	fixtures, blocks := proc2Rewrite(t, ".")
	if base != "." {
		// std/proc comes from the tree, the rest from the base.
		ents, err := os.ReadDir("proc")
		if err != nil {
			t.Fatal(err)
		}
		for _, e := range ents {
			k := "proc/" + e.Name()
			if _, ok := fixtures[k]; !ok && strings.HasSuffix(k, ".mk") {
				b, err := os.ReadFile(filepath.FromSlash(k))
				if err != nil {
					t.Fatal(err)
				}
				fixtures[k] = string(b)
			}
		}
	}
	if len(blocks) == 0 {
		t.Fatal("no test blocks found")
	}
	root := t.TempDir()
	stdDir := proc2CopyStd(t, root, base, fixtures)
	if err := os.WriteFile(filepath.Join(root, "main.mk"), []byte(proc2Main), 0o644); err != nil {
		t.Fatal(err)
	}
	exe := filepath.Join(root, "main")
	if linux {
		flags = append(flags, "--target", "x86_64-linux")
	} else if runtime.GOOS == "windows" {
		exe += ".exe"
	}
	args := append([]string{"build"}, flags...)
	args = append(args, "-o", exe, "main.mk")
	out, status := mkCmd(t, root, stdDir, args...)
	if status != 0 {
		if strings.Contains(out, "no usable LLVM") {
			t.Skipf("needs the LLVM toolchain: %s", out)
		}
		t.Fatalf("mk build: exit %d\n%s", status, out)
	}
	return exe, blocks
}

// proc2Only filters blocks by MK_PROC2_ONLY (a substring of the name).
func proc2Only(blocks []proc2Block) []int {
	only := os.Getenv("MK_PROC2_ONLY")
	var idx []int
	for i, b := range blocks {
		if only == "" || strings.Contains(b.name, only) {
			idx = append(idx, i)
		}
	}
	return idx
}

// proc2Blocks builds the runner (dev and release) and runs each block with
// 1 and 8 carriers on host h; on Linux once per backend (io_uring, which
// MK_IO=auto picks on WSL's kernel, and epoll), so both give the same
// results.
func proc2Blocks(t *testing.T, h ioHost) {
	backends := []string{""}
	if h.linux {
		backends = []string{"MK_IO=auto", "MK_IO=epoll"}
	}
	for _, mode := range []string{"dev", "release"} {
		t.Run(mode, func(t *testing.T) {
			var flags []string
			if mode == "release" {
				flags = append(flags, "--release")
			}
			exe, blocks := proc2Build(t, h.linux, flags...)
			idx := proc2Only(blocks)
			carriers := []int{1, 8}
			type variant struct {
				carriers int
				backend  string
			}
			var vs []variant
			for _, be := range backends {
				for _, n := range carriers {
					vs = append(vs, variant{n, be})
				}
			}
			var calls []ioCall
			for _, v := range vs {
				for _, i := range idx {
					env := []string{fmt.Sprintf("MK_CARRIERS=%d", v.carriers)}
					if v.backend != "" {
						env = append(env, v.backend)
					}
					calls = append(calls, ioCall{env: env, watch: 120, args: []string{fmt.Sprint(i)}})
				}
			}
			runs := h.runMany(t, exe, calls)
			for k, r := range runs {
				b := blocks[idx[k%len(idx)]]
				v := vs[k/len(idx)]
				name := fmt.Sprintf("%s/carriers=%d", b.name, v.carriers)
				if v.backend != "" {
					name += "/" + strings.TrimPrefix(v.backend, "MK_IO=")
				}
				t.Run(name, func(t *testing.T) {
					if r.code == 124 {
						t.Fatalf("no exit within %d s\nstdout: %s\nstderr: %s", calls[k].watch, stdioTail(r.stdout), stdioTail(r.stderr))
					}
					if r.code != 0 {
						t.Fatalf("exit %d\nstdout: %s\nstderr: %s", r.code, stdioTail(r.stdout), stdioTail(r.stderr))
					}
				})
			}
		})
	}
}

// TestProc_RunBlocks runs std.proc's blocks on the host.
func TestProc_RunBlocks(t *testing.T) { proc2Blocks(t, hostIo) }

// TestProc_RunLinuxBlocks runs them as x86_64-linux programs under WSL.
func TestProc_RunLinuxBlocks(t *testing.T) {
	linuxGate(t)
	stdioNeedWSL(t)
	proc2Blocks(t, linuxIo)
}

// TestProc_RunBlockNames: every block of the runner's files has a function,
// and no two share a name (the runner names its subtests by block name and
// MK_PROC2_ONLY selects by it).
func TestProc_RunBlockNames(t *testing.T) {
	_, blocks := proc2Rewrite(t, ".")
	if len(blocks) == 0 {
		t.Fatal("no blocks")
	}
	seen := map[string]bool{}
	for _, b := range blocks {
		if seen[b.name] {
			t.Errorf("two blocks are named %q", b.name)
		}
		seen[b.name] = true
	}
	if slices.ContainsFunc(blocks, func(b proc2Block) bool { return b.fn == "" }) {
		t.Error("a block has no function")
	}
}
