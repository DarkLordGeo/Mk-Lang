// Why: std.sim's path cleaning and random generator must match independent models,
// or a seed would not mean the same run everywhere.
// What: TestSTDSIM_CleanPathMatchesGo and TestSTDSIM_RngMatchesReference.
// How: CleanPath against Go's path.Clean with \ read as /; the generator (xoshiro256**
// seeded by SplitMix64, Lemire's bounded draw) against a Go implementation
// from the published algorithms.
//
// Each test writes a generated block file into a copy of std/sim and runs it
// with mk test --std=std.sim, so the Mk side runs the module's own private
// functions.

package std

import (
	"fmt"
	"math/bits"
	"math/rand/v2"
	"path"
	"strings"
	"testing"
)

// simMkQuote is s as an Mk string literal.
func simMkQuote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		switch c := s[i]; c {
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// simCleanCases are the edge cases plus n random strings over {a, ., /, \}
// of length 0 to 40, from a fixed seed.
func simCleanCases(n int) []string {
	cases := []string{"", ".", "..", "/", "\\", "/..", "../..", "a/../..", "a/b/../../..", "//a//b//",
		"./a/./b/.", "a\\..\\b", "\\\\a\\\\", "...", "a/...", "/./", ".a/..b/", "a/b/c/../../../../d"}
	r := rand.New(rand.NewPCG(18, 0x5EED))
	alpha := []byte{'a', '.', '/', '\\'}
	for len(cases) < n {
		k := r.IntN(41)
		b := make([]byte, k)
		for i := range b {
			b[i] = alpha[r.IntN(len(alpha))]
		}
		cases = append(cases, string(b))
	}
	return cases
}

// runSimFixture runs mk test --std=std.sim over std with the generated
// block file added, at dev and release, and wants the named block to pass.
func runSimFixture(t *testing.T, file, block, src string) {
	t.Helper()
	for _, flags := range [][]string{nil, {"--release"}} {
		root := t.TempDir()
		stdDir := copyStd(t, root, map[string]string{"sim/" + file: src})
		out, _ := mkCmd(t, root, stdDir, append([]string{"test", "--std=std.sim"}, flags...)...)
		if strings.Contains(out, "no usable LLVM") {
			t.Skipf("needs the LLVM toolchain: %s", out)
		}
		res := parseStdTest(out, "std.sim")
		if r, ok := res[block]; !ok || !r.pass {
			t.Fatalf("%v: block %q: %+v\n%s", flags, block, r, out)
		}
	}
}

// TestSTDSIM_CleanPathMatchesGo: 1,000 paths (the edge cases and random
// ones), each checked on its own line, so a failing assert names its case.
func TestSTDSIM_CleanPathMatchesGo(t *testing.T) {
	t.Parallel()
	const block = "SIM-R18: CleanPath matches Go's path.Clean"
	var b strings.Builder
	b.WriteString("// Generated by std/std-sim_ref_test.go (TestSTDSIM_CleanPathMatchesGo).\n\n")
	b.WriteString("RefClean(p: str, want: str): bool {\n    var buf: [4096]u8 = [0; 4096]\n")
	b.WriteString("    n := CleanPath(p, mut buf[..])\n    return n >= 0 && BytesEq(buf[0..n], want.AsBytes())\n}\n\n")
	fmt.Fprintf(&b, "test %q (sys: &System) {\n", block)
	for _, c := range simCleanCases(1000) {
		want := path.Clean(strings.ReplaceAll(c, `\`, "/"))
		fmt.Fprintf(&b, "    Assert(RefClean(%s, %s))\n", simMkQuote(c), simMkQuote(want))
	}
	b.WriteString("}\n")
	runSimFixture(t, "tests_ref_clean.mk", block, b.String())
}

// The Go reference generator.
type simXoshiro struct{ s [4]uint64 }

func simSplitmix(x uint64) uint64 {
	x = (x ^ (x >> 30)) * 0xBF58476D1CE4E5B9
	x = (x ^ (x >> 27)) * 0x94D049BB133111EB
	return x ^ (x >> 31)
}

// newSimXoshiro seeds the state with SplitMix64's first four outputs from
// state seed (the generator adds the golden gamma before each output).
func newSimXoshiro(seed uint64) *simXoshiro {
	const gamma = 0x9E3779B97F4A7C15
	var x simXoshiro
	st := seed
	for i := range x.s {
		st += gamma
		x.s[i] = simSplitmix(st)
	}
	return &x
}

func (x *simXoshiro) next() uint64 {
	s := &x.s
	result := bits.RotateLeft64(s[1]*5, 7) * 9
	t := s[1] << 17
	s[2] ^= s[0]
	s[3] ^= s[1]
	s[1] ^= s[2]
	s[0] ^= s[3]
	s[2] ^= t
	s[3] = bits.RotateLeft64(s[3], 45)
	return result
}

// below is Lemire's nearly divisionless bounded draw (Lemire 2019).
func (x *simXoshiro) below(n uint64) uint64 {
	hi, lo := bits.Mul64(x.next(), n)
	if lo < n {
		thresh := -n % n
		for lo < thresh {
			hi, lo = bits.Mul64(x.next(), n)
		}
	}
	return hi
}

// simFnvU64 is record.mk's FnvU64: FNV-1a over x's eight bytes, low first.
func simFnvU64(d, x uint64) uint64 {
	for k := 0; k < 8; k++ {
		d = (d ^ ((x >> (8 * k)) & 0xFF)) * 0x100000001B3
	}
	return d
}

// TestSTDSIM_RngMatchesReference: for seeds 0 to 10 the digest of the first
// 1,000 Next values, and for seed 7 the digests of 200 Below draws for n in
// 1, 3, 2^63 + 1 and 10^9, equal the Go model's.
func TestSTDSIM_RngMatchesReference(t *testing.T) {
	t.Parallel()
	const block = "SIM-R18: the world's generator matches a Go xoshiro256** model"
	const fnvSeed = 0xCBF29CE484222325
	var b strings.Builder
	b.WriteString("// Generated by std/std-sim_ref_test.go (TestSTDSIM_RngMatchesReference).\n\n")
	b.WriteString("RefNext(a: &Arena, seed: u64, want: u64): bool {\n")
	b.WriteString("    var s := Sim.New(a, seed) else {\n        return false\n    }\n")
	b.WriteString("    LockSlot(s.slot)\n    w := s.World()\n    var d: u64 = FnvSeed\n")
	b.WriteString("    for _ in 0..1000 {\n        d = FnvU64(d, w.Next())\n    }\n    UnlockSlot(s.slot)\n")
	b.WriteString("    s.Free()\n    return d == want\n}\n\n")
	b.WriteString("RefBelow(a: &Arena, seed: u64, n: u64, want: u64): bool {\n")
	b.WriteString("    var s := Sim.New(a, seed) else {\n        return false\n    }\n")
	b.WriteString("    LockSlot(s.slot)\n    w := s.World()\n    var d: u64 = FnvSeed\n")
	b.WriteString("    for _ in 0..200 {\n        d = FnvU64(d, w.Below(n))\n    }\n    UnlockSlot(s.slot)\n")
	b.WriteString("    s.Free()\n    return d == want\n}\n\n")
	fmt.Fprintf(&b, "test %q (sys: &System) {\n", block)
	for seed := uint64(0); seed <= 10; seed++ {
		x := newSimXoshiro(seed)
		d := uint64(fnvSeed)
		for i := 0; i < 1000; i++ {
			d = simFnvU64(d, x.next())
		}
		fmt.Fprintf(&b, "    Assert(RefNext(sys.arena, %d, 0x%X))\n", seed, d)
	}
	for _, n := range []uint64{1, 3, 1<<63 + 1, 1_000_000_000} {
		x := newSimXoshiro(7)
		d := uint64(fnvSeed)
		for i := 0; i < 200; i++ {
			d = simFnvU64(d, x.below(n))
		}
		fmt.Fprintf(&b, "    Assert(RefBelow(sys.arena, 7, 0x%X, 0x%X))\n", n, d)
	}
	b.WriteString("}\n")
	runSimFixture(t, "tests_ref_rng.mk", block, b.String())
}
