// Why: std.time.tzdata embeds the zone database, and the committed file must
// match the pinned source byte for byte.
// What: TestStdTime_TzdataUpToDate, the generator of std/time/tzdata/zones.mk.
// How: reads compiled TZif (never tz source) from the pinned Mk-evidence/iana/zoneinfo.zip,
// the zones of the Go release used as the oracle; links share one copy.
//
//	go test ./std -run TestStdTime_TzdataUpToDate -update

package std

import (
	"archive/zip"
	"bytes"
	"crypto/sha256"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

// time2Evidence is Mk-evidence/<rel> ($MK_EVIDENCE, else next to the
// repository), or "" when it is missing.
func time2Evidence(rel string) string {
	root := os.Getenv("MK_EVIDENCE")
	if root == "" {
		root = filepath.Join("..", "..", "Mk-evidence")
	}
	p := filepath.Join(root, filepath.FromSlash(rel))
	if _, err := os.Stat(p); err != nil {
		return ""
	}
	return p
}

// time2Zone is one zone of the pinned database.
type time2Zone struct {
	name string
	data []byte
}

// time2Zones reads every zone of zoneinfo.zip, sorted by name, and the
// IANA release SOURCE.txt records. It skips t when the evidence is missing.
func time2Zones(t testing.TB) ([]time2Zone, string, [32]byte) {
	t.Helper()
	zp := time2Evidence("iana/zoneinfo.zip")
	if zp == "" {
		t.Skip("Mk-evidence/iana/zoneinfo.zip not found (set MK_EVIDENCE)")
	}
	raw, err := os.ReadFile(zp)
	if err != nil {
		t.Fatal(err)
	}
	src, err := os.ReadFile(filepath.Join(filepath.Dir(zp), "SOURCE.txt"))
	if err != nil {
		t.Fatal(err)
	}
	release := ""
	if i := bytes.Index(src, []byte("IANA tz release ")); i >= 0 {
		f := strings.Fields(string(src[i+len("IANA tz release "):]))
		if len(f) > 0 {
			release = strings.TrimRight(f[0], ".,(")
		}
	}
	if release == "" {
		t.Fatal("iana/SOURCE.txt names no IANA tz release")
	}
	zr, err := zip.NewReader(bytes.NewReader(raw), int64(len(raw)))
	if err != nil {
		t.Fatal(err)
	}
	var zones []time2Zone
	for _, f := range zr.File {
		if strings.HasSuffix(f.Name, "/") {
			continue
		}
		rc, err := f.Open()
		if err != nil {
			t.Fatal(err)
		}
		b, err := io.ReadAll(rc)
		rc.Close()
		if err != nil {
			t.Fatal(err)
		}
		zones = append(zones, time2Zone{f.Name, b})
	}
	sort.Slice(zones, func(i, j int) bool { return zones[i].name < zones[j].name })
	return zones, release, sha256.Sum256(raw)
}

// time2Bytes writes b as the body of an Mk byte string literal.
func time2Bytes(sb *strings.Builder, b []byte) {
	for _, c := range b {
		if c >= 0x20 && c < 0x7F && c != '"' && c != '\\' {
			sb.WriteByte(c)
		} else {
			fmt.Fprintf(sb, "\\x%02x", c)
		}
	}
}

// time2Table writes const name: [len]typ = [...] with sixteen values a line.
func time2Table(sb *strings.Builder, name, typ string, vals []int) {
	fmt.Fprintf(sb, "const %s: [%d]%s = [\n", name, len(vals), typ)
	for i := 0; i < len(vals); i += 16 {
		sb.WriteString("   ")
		for j := i; j < i+16 && j < len(vals); j++ {
			fmt.Fprintf(sb, " %d,", vals[j])
		}
		sb.WriteString("\n")
	}
	sb.WriteString("]\n")
}

// time2Generate is std/time/tzdata/zones.mk.
func time2Generate(t testing.TB) string {
	zones, release, sum := time2Zones(t)
	var sb strings.Builder
	fmt.Fprintf(&sb, "// Code generated by std/std-time_tzdata_test.go from the IANA tz database. DO NOT EDIT.\n")
	fmt.Fprintf(&sb, "// The compiled zones of Go's zoneinfo.zip (SHA-256 %x),\n", sum)
	fmt.Fprintf(&sb, "// the Go release std.time is tested against; the tz data is in the public domain.\n")
	fmt.Fprintf(&sb, "// Regenerate with go test ./std -run TestStdTime_TzdataUpToDate -update.\n")
	fmt.Fprintf(&sb, "// IANA tz release: %s\n\n", release)
	fmt.Fprintf(&sb, "// Release is the IANA tz release the zones are from.\n")
	fmt.Fprintf(&sb, "const Release: str = \"%s\"\n\n", release)

	// Unique zone bytes in first-name order, so a link shares its target.
	index := map[string]int{}
	var blobs [][]byte
	var names strings.Builder
	var nameEnd, nameZone, zoneEnd []int
	total := 0
	for _, z := range zones {
		k, ok := index[string(z.data)]
		if !ok {
			k = len(blobs)
			index[string(z.data)] = k
			blobs = append(blobs, z.data)
			total += len(z.data)
			zoneEnd = append(zoneEnd, total)
		}
		names.WriteString(z.name)
		nameEnd = append(nameEnd, names.Len())
		nameZone = append(nameZone, k)
	}
	fmt.Fprintf(&sb, "// %d names, %d distinct zones, %d bytes of TZif. NameText holds\n", len(zones), len(blobs), total)
	fmt.Fprintf(&sb, "// the names sorted and joined; name i ends at NameEnd[i] and is zone\n")
	fmt.Fprintf(&sb, "// NameZone[i]; zone k ends at ZoneEnd[k] in ZoneData.\n")
	fmt.Fprintf(&sb, "const NameText: str = \"%s\"\n\n", names.String())
	time2Table(&sb, "NameEnd", "u16", nameEnd)
	sb.WriteString("\n")
	time2Table(&sb, "NameZone", "u16", nameZone)
	sb.WriteString("\n")
	time2Table(&sb, "ZoneEnd", "u32", zoneEnd)
	sb.WriteString("\nconst ZoneData: []u8 = b\"")
	for _, b := range blobs {
		time2Bytes(&sb, b)
	}
	sb.WriteString("\"\n")
	return sb.String()
}

func TestStdTime_TzdataUpToDate(t *testing.T) {
	want := time2Generate(t)
	p := filepath.Join("time", "tzdata", "zones.mk")
	if *update {
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(p)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Fatalf("%s is stale: go test ./std -run TestStdTime_TzdataUpToDate -update", p)
	}
}
