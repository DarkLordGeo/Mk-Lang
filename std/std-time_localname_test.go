// Why: time.LocalName (std/time/localname.mk) maps Windows zone names to IANA
// names through a generated table that must match CLDR and the OS.
// What: TestStdTime_WindowsZonesUpToDate, which writes std/time/windows_zones.mk,
// and TestStdTime_LocalName.
// How: the table is the territory "001" row of each Windows zone in CLDR's
// windowsZones.xml (Mk-evidence/cldr, release 49); LocalName is checked for
// every row and against the zone the OS reports.
//
//	go test ./std -run TestStdTime_WindowsZonesUpToDate -update

package std

import (
	"encoding/xml"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
	"testing"
)

// time2WinZone is one row: a Windows zone key name and its IANA name.
type time2WinZone struct{ win, iana string }

// time2WinZones reads the territory "001" rows of windowsZones.xml,
// sorted by Windows name.
func time2WinZones(t testing.TB) ([]time2WinZone, string) {
	t.Helper()
	p := time2Evidence("cldr/windowsZones.xml")
	if p == "" {
		t.Skip("Mk-evidence/cldr/windowsZones.xml not found (set MK_EVIDENCE)")
	}
	raw, err := os.ReadFile(p)
	if err != nil {
		t.Fatal(err)
	}
	var doc struct {
		Zones struct {
			TypeVersion string `xml:"typeVersion,attr"`
			Map         []struct {
				Other     string `xml:"other,attr"`
				Territory string `xml:"territory,attr"`
				Type      string `xml:"type,attr"`
			} `xml:"mapZone"`
		} `xml:"windowsZones>mapTimezones"`
	}
	if err := xml.Unmarshal(raw, &doc); err != nil {
		t.Fatal(err)
	}
	var out []time2WinZone
	for _, m := range doc.Zones.Map {
		if m.Territory == "001" {
			out = append(out, time2WinZone{m.Other, strings.Fields(m.Type)[0]})
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].win < out[j].win })
	return out, doc.Zones.TypeVersion
}

// time2WinGenerate is std/time/windows_zones.mk.
func time2WinGenerate(t testing.TB) string {
	rows, version := time2WinZones(t)
	var sb strings.Builder
	sb.WriteString("// Code generated by std/std-time_localname_test.go from Unicode CLDR. DO NOT EDIT.\n")
	sb.WriteString("// The territory \"001\" IANA zone of each Windows zone key name, from CLDR release 49's\n")
	fmt.Fprintf(&sb, "// windowsZones.xml (typeVersion %s; Copyright Unicode, Inc., under the Unicode License v3).\n", version)
	sb.WriteString("// Regenerate with go test ./std -run TestStdTime_WindowsZonesUpToDate -update.\n\n")
	var win, iana strings.Builder
	var we, ie []int
	for _, r := range rows {
		win.WriteString(r.win)
		we = append(we, win.Len())
		iana.WriteString(r.iana)
		ie = append(ie, iana.Len())
	}
	fmt.Fprintf(&sb, "// %d zones. Windows name i ends at WinEnd[i] in WinText, sorted; its\n", len(rows))
	sb.WriteString("// IANA name ends at IanaEnd[i] in IanaText.\n")
	fmt.Fprintf(&sb, "const WinText: str = %q\n\n", win.String())
	time2Table(&sb, "WinEnd", "u16", we)
	fmt.Fprintf(&sb, "\nconst IanaText: str = %q\n\n", iana.String())
	time2Table(&sb, "IanaEnd", "u16", ie)
	return sb.String()
}

func TestStdTime_WindowsZonesUpToDate(t *testing.T) {
	want := time2WinGenerate(t)
	p := filepath.Join("time", "windows_zones.mk")
	if *update {
		if err := os.WriteFile(p, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(p)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Fatalf("%s is stale: go test ./std -run TestStdTime_WindowsZonesUpToDate -update", p)
	}
}

// time2NameProg prints LocalName, then the IANA name of each Windows name
// on stdin through the table ("-" for none).
const time2NameProg = `import std.time

export Main(sys: &System): WriteError|ReadError|OutOfMemory!void {
    var out := sys.Stdout()
    n := time.LocalName(sys.arena, sys.io) else { "-" }
    try Print(mut out, "{n}\n", (n))
    var inp := sys.Stdin()
    for {
        line := try inp.Line(sys.arena) else {
            return
        }
        z := time.IanaOfWindows(line) else { "-" }
        try Print(mut out, "{z}\n", (z))
    }
}
`

func TestStdTime_LocalName(t *testing.T) {
	rows, _ := time2WinZones(t)
	var in strings.Builder
	for _, r := range rows {
		in.WriteString(r.win + "\n")
	}
	in.WriteString("Not A Zone\n\n")
	// The program names IanaOfWindows, which std.time does not export:
	// the test builds it with a fixture that exports a wrapper.
	fix := map[string]string{"time/localname_export.mk": "/// Test-only.\nexport IanaOfWindows(win: str): ?str {\n    return IanaOf(win)\n}\n"}
	exe := time2Build(t, fix, time2NameProg)
	cmd := exec.Command(exe)
	cmd.Stdin = strings.NewReader(in.String())
	out, err := cmd.Output()
	if err != nil {
		t.Fatal(err)
	}
	got := strings.Split(strings.TrimRight(strings.ReplaceAll(string(out), "\r\n", "\n"), "\n"), "\n")
	if len(got) != len(rows)+3 {
		t.Fatalf("%d answers for %d names", len(got), len(rows)+2)
	}
	for i, r := range rows {
		if got[1+i] != r.iana {
			t.Errorf("IanaOf(%q) = %q, CLDR %q", r.win, got[1+i], r.iana)
		}
	}
	if got[1+len(rows)] != "-" || got[2+len(rows)] != "-" {
		t.Errorf("an unknown name maps to %q and %q, want none", got[1+len(rows)], got[2+len(rows)])
	}
	// On Windows LocalName is the CLDR zone of the key name the OS
	// reports (tzutil /g prints the same key).
	if runtime.GOOS == "windows" {
		key, err := exec.Command("tzutil", "/g").Output()
		if err != nil {
			t.Skipf("tzutil /g: %v", err)
		}
		want := "-"
		for _, r := range rows {
			if r.win == strings.TrimSpace(string(key)) {
				want = r.iana
			}
		}
		if got[0] != want {
			t.Errorf("LocalName = %q; the OS's zone %q is %q in CLDR", got[0], strings.TrimSpace(string(key)), want)
		}
	}
}
