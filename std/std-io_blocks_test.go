// Why: the test blocks of std.fs, std.time, std.proc and std.net must pass
// at both 1 and 8 carriers, which one program holding every block can drive.
// What: TestStdIo_TestBlocks and the block rewriter it uses.
// How: in a copy of std, every `test` block of fs, time, proc and net
// becomes an exported function of its module, and a fixture proc/zprobe.mk
// calls the one a command-line index names. Each run starts the one
// executable for one block under a watchdog, with MK_CARRIERS 1 and 8; a
// block passes when its process exits 0 (a failed Assert is a panic, 101).
// std/rt-sched_harness_test.go does the same rewrite for its own modules.

package std

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"testing"
)

// ioBlock is one rewritten test block.
type ioBlock struct {
	name   string // the block's name, which starts with its requirement ID
	module string // fs, time, proc or net
	fn     string // the exported function it became
}

var ioBlockHeader = regexp.MustCompile(`^test "([^"]*)"\s*(\(sys: &System\))?\s*\{\s*$`)

// ioBlockErrors is a rewritten block's error set, spelled the same in each
// module (Error is the module's own). A test's try and fail are not checked
// (reference 4.12.2), an exported function's are; the probe panics when a
// block returns an error, as a failed test.
const ioBlockErrors = "Error|OutOfMemory|WriteError"

// ioBlockModules are the modules whose tests_*.mk this harness runs.
var ioBlockModules = []string{"fs", "time", "proc", "net"}

// ioBlockSet is the error set of a rewritten block of module in a file
// with text: ioBlockErrors and the Error of each of ioBlockModules the
// file imports.
func ioBlockSet(module, text string) string {
	set := ioBlockErrors
	for _, m := range ioBlockModules {
		if m != module && regexp.MustCompile(`(?m)^import std\.`+m+`\s*$`).MatchString(text) {
			set += "|" + m + ".Error"
		}
	}
	return set
}

// ioBlocksRewrite returns the fixtures (the rewritten test files and the
// probe) and the blocks in a fixed order (module, file, line).
func ioBlocksRewrite(t *testing.T) (map[string]string, []ioBlock) {
	t.Helper()
	fixtures := map[string]string{}
	var blocks []ioBlock
	for _, module := range ioBlockModules {
		files, err := filepath.Glob(filepath.Join(module, "tests_*.mk"))
		if err != nil {
			t.Fatal(err)
		}
		sort.Strings(files)
		for _, f := range files {
			b, err := os.ReadFile(f)
			if err != nil {
				t.Fatal(err)
			}
			text := strings.ReplaceAll(string(b), "\r\n", "\n")
			set := ioBlockSet(module, text)
			lines := strings.Split(text, "\n")
			for i, line := range lines {
				m := ioBlockHeader.FindStringSubmatch(line)
				if m == nil {
					continue
				}
				fn := fmt.Sprintf("ZzIoTest%d", len(blocks))
				lines[i] = "export " + fn + "(sys: &System): " + set + "!void {"
				blocks = append(blocks, ioBlock{name: m[1], module: module, fn: fn})
			}
			fixtures[filepath.ToSlash(f)] = strings.Join(lines, "\n")
		}
	}
	var p strings.Builder
	p.WriteString("// Generated by std/std-io_blocks_test.go.\n\nimport std.fs\nimport std.net\nimport std.time\n\n")
	p.WriteString("export ZzIoRun(sys: &System, i: int): bool {\n")
	for i, b := range blocks {
		call := b.module + "." + b.fn
		if b.module == "proc" {
			call = b.fn
		}
		fmt.Fprintf(&p, "    if i == %d {\n        %s(sys) else {\n            ZzIoFailed(sys, %q)\n        }\n        return true\n    }\n", i, call, b.name)
	}
	p.WriteString("    return false\n}\n")
	p.WriteString("\nZzIoFailed(sys: &System, name: str) {\n    var w := sys.Stderr()\n    _ = Print(mut w, \"{name}: an error ended the block\\n\", (name)) else {}\n    _ = w.Flush() else {}\n    Panic(\"a test block failed with an error\")\n}\n")
	fixtures["proc/zprobe.mk"] = p.String()
	return fixtures, blocks
}

// ioBlocksMain runs the block whose index is the first argument; exit 0
// when it returned, 2 for an unknown index.
const ioBlocksMain = `import std.proc

export Main(sys: &System): int {
    if sys.args.Len() < 2 {
        return 2
    }
    var n := 0
    for b in sys.args[1].AsBytes() {
        n = n * 10 + int(b) - 48
    }
    if !proc.ZzIoRun(sys, n) {
        return 2
    }
    return 0
}
`

// TestStdIo_TestBlocks runs every test block of ioBlockModules with
// 1 and 8 carriers. A net block that panics with "net.Listen failed" is
// BLOCKED while the runtime's socket entries are stubs.
func TestStdIo_TestBlocks(t *testing.T) { stdIoBlocks(t, hostIo) }

func stdIoBlocks(t *testing.T, h ioHost) {
	fixtures, blocks := ioBlocksRewrite(t)
	if len(blocks) == 0 {
		t.Fatal("no test blocks found")
	}
	exe := h.build(t, fixtures, ioBlocksMain)
	carriers := []int{1, 8}
	var calls []ioCall
	for _, n := range carriers {
		for i := range blocks {
			calls = append(calls, ioCall{env: []string{fmt.Sprintf("MK_CARRIERS=%d", n)}, watch: 60, args: []string{fmt.Sprint(i)}})
		}
	}
	runs := h.runMany(t, exe, calls)
	for k, r := range runs {
		b := blocks[k%len(blocks)]
		name := fmt.Sprintf("%s/%s/carriers=%d", b.module, b.name, carriers[k/len(blocks)])
		t.Run(name, func(t *testing.T) {
			if b.module == "net" && r.code == 101 && strings.Contains(r.stderr, "net.Listen failed") {
				t.Skipf("BLOCKED: the runtime's listen entry fails (stubs in std/task/io_misc.mk)")
			}
			if r.code == 124 {
				t.Fatalf("no exit within %d s", calls[k].watch)
			}
			if r.code != 0 {
				t.Fatalf("exit %d\nstdout: %s\nstderr: %s", r.code, stdioTail(r.stdout), stdioTail(r.stderr))
			}
		})
	}
}
