// Why: a std.math function must give the same bits at compile time, at dev,
// at release and on every target.
// What: the identity test and mathIdentity, each function's pinned hash.
// How: one fixed input set runs in the evaluator and natively (natively Fma
// is the instruction where the CPU has fma); the FNV-1a hash of the result
// bits must agree and match the pin (Linux under MK_LINUX=1).

package std

