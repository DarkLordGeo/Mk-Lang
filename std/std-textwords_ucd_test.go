// Why: std/text/bounds_tables.mk is generated data; it must match the UCD it
// claims and stay small.
// What: the table generator, TestSTDTEXT_WordsTablesUpToDate, TableBytes and
// AsciiPremise.
// How: reads the UCD files under $MK_EVIDENCE/ucd (every Unicode table of std
// comes from one UCD version) and regenerates the tables to compare.

// The generator of std/text/bounds_tables.mk, the Word_Break
// and Sentence_Break data of UAX 29 that text.WordBounds and
// text.SentenceBounds read, from the UCD files under $MK_EVIDENCE/ucd,
// and the Go reference models of both segmentations. The models
// follow UAX 29's rules one position at a time, rule by rule, looking left
// and right through the transformed sequence (WB4, SB5) as the annex
// states them; the Mk code is a single forward scan with state, so the two
// share the rules, not the algorithm. The models must pass every line of
// the UCD's WordBreakTest.txt and SentenceBreakTest.txt before they judge
// the Mk code (TestSTDTEXT_WordsModelsMatchUCDTests).

package std

