// The Word_Break values, in the order std/text/bounds_tables.mk numbers
// them (the low five bits of a WordProp byte).
const (
	wbOther = iota
	wbCR
	wbLF
	wbNewline
	wbExtend
	wbZWJ
	wbRI
	wbFormat
	wbKatakana
	wbHebrewLetter
	wbALetter
	wbSingleQuote
	wbDoubleQuote
	wbMidNumLet
	wbMidLetter
	wbMidNum
	wbNumeric
	wbExtendNumLet
	wbWSegSpace
	wbCount
)

var wbNames = []string{
	"Other", "CR", "LF", "Newline", "Extend", "ZWJ", "Regional_Indicator",
	"Format", "Katakana", "Hebrew_Letter", "ALetter", "Single_Quote",
	"Double_Quote", "MidNumLet", "MidLetter", "MidNum", "Numeric",
	"ExtendNumLet", "WSegSpace",
}

// wbExtPict is the WordProp bit for Extended_Pictographic (WB3c).
const wbExtPict = 1 << 5

// The Sentence_Break values, in the order of the SentProp bytes.
const (
	sbOther = iota
	sbCR
	sbLF
	sbSep
	sbExtend
	sbFormat
	sbSp
	sbLower
	sbUpper
	sbOLetter
	sbNumeric
	sbATerm
	sbSTerm
	sbClose
	sbSContinue
	sbCount
)

var sbNames = []string{
	"Other", "CR", "LF", "Sep", "Extend", "Format", "Sp", "Lower", "Upper",
	"OLetter", "Numeric", "ATerm", "STerm", "Close", "SContinue",
}

// segData is the Word_Break and Sentence_Break value of every scalar.
type segData struct {
	version string
	wb      []uint8 // with wbExtPict
	sb      []uint8
}

var (
	segOnce sync.Once
	segVal  *segData
	segErr  error
)

// needSeg parses the two property files once per test binary (skipping
// the test when the UCD is absent, as needUCD does).
func needSeg(t *testing.T) *segData {
	t.Helper()
	u := needUCD(t)
	segOnce.Do(func() { segVal, segErr = parseSeg(ucdDir(), u) })
	if segErr != nil {
		t.Fatal(segErr)
	}
	return segVal
}

func parseSeg(dir string, u *ucd) (*segData, error) {
	const n = 0x110000
	d := &segData{wb: make([]uint8, n), sb: make([]uint8, n)}
	read := func(file string, names []string, dst []uint8) (string, error) {
		idx := map[string]uint8{}
		for i, s := range names {
			idx[s] = uint8(i)
		}
		return ucdLines(dir, file, func(f []string) error {
			if len(f) < 2 {
				return fmt.Errorf("want two fields")
			}
			lo, hi, err := ucdRange(f[0])
			if err != nil {
				return err
			}
			v, ok := idx[f[1]]
			if !ok {
				return fmt.Errorf("unknown value %q", f[1])
			}
			for c := lo; c <= hi; c++ {
				dst[c] = v
			}
			return nil
		})
	}
	v1, err := read("auxiliary/WordBreakProperty.txt", wbNames, d.wb)
	if err != nil {
		return nil, err
	}
	v2, err := read("auxiliary/SentenceBreakProperty.txt", sbNames, d.sb)
	if err != nil {
		return nil, err
	}
	if v1 != u.version || v2 != u.version {
		return nil, fmt.Errorf("UCD versions differ: UnicodeData %s, WordBreakProperty %s, SentenceBreakProperty %s", u.version, v1, v2)
	}
	for c := range d.wb {
		if u.extPict[c] {
			d.wb[c] |= wbExtPict
		}
	}
	d.version = v1
	return d, nil
}

// genBoundsTables returns the text of std/text/bounds_tables.mk.
func genBoundsTables(d *segData) string {
	var b strings.Builder
	fmt.Fprintf(&b, `// Code generated by std/std-textwords_ucd_test.go from the Unicode Character Database. DO NOT EDIT.
// The UAX 29 Word_Break and Sentence_Break data that WordBounds and SentenceBounds
// read. UCD data Copyright Unicode, Inc., under the Unicode License v3. Regenerate with
// go test ./std -run TestSTDTEXT_WordsTablesUpToDate -update (UCD files in $MK_EVIDENCE/ucd).
// UCD version: %s

`, d.version)
	wb := make([]int, len(d.wb))
	sb := make([]int, len(d.sb))
	for c := range wb {
		wb[c] = int(d.wb[c])
		sb[c] = int(d.sb[c])
	}
	b.WriteString(`// WordProp bytes: bits 0 to 4 Word_Break (Wb*), bit 5
// Extended_Pictographic (WordExtPict). WordAscii is the first 128.
`)
	writeArray(&b, "WordAscii", "u8", wb[:128], false)
	writeTrie3(&b, "WordProp", buildTrie3(wb))
	b.WriteString("// SentProp bytes: Sentence_Break (Sb*). SentAscii is the first 128.\n")
	writeArray(&b, "SentAscii", "u8", sb[:128], false)
	writeTrie3(&b, "SentProp", buildTrie3(sb))
	return strings.TrimRight(b.String(), "\n") + "\n"
}

// boundsTablesPath is the generated file, relative to std/.
const boundsTablesPath = "text/bounds_tables.mk"

// TestSTDTEXT_WordsTablesUpToDate regenerates std/text/bounds_tables.mk from
// the UCD and requires the committed file to equal it; -update rewrites it.
func TestSTDTEXT_WordsTablesUpToDate(t *testing.T) {
	d := needSeg(t)
	want := genBoundsTables(d)
	if *update {
		if err := os.WriteFile(boundsTablesPath, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote %s (%d bytes), UCD %s", boundsTablesPath, len(want), d.version)
		return
	}
	got, err := os.ReadFile(boundsTablesPath)
	if err != nil {
		t.Fatal(err)
	}
	if strings.ReplaceAll(string(got), "\r\n", "\n") != want {
		t.Fatalf("%s is not what the UCD %s files give; run go test ./std -run TestSTDTEXT_WordsTablesUpToDate -update", boundsTablesPath, d.version)
	}
}

// trie3 is a three-stage table: Index1[c >> (s2 + s3)] is a block of
// Index2, whose entry for (c >> s3) & (2^s2 - 1) is a block of Data.
type trie3 struct {
	s2, s3 int
	i1, i2 []int
	data   []int
}

// width is the bytes of one entry of a table indexing n blocks.
func trie3Width(n int) int {
	if n > 256 {
		return 2
	}
	return 1
}

func (tr trie3) bytes() int {
	return len(tr.i1)*trie3Width(len(tr.i2)>>tr.s2) + len(tr.i2)*trie3Width(len(tr.data)>>tr.s3) + len(tr.data)
}

// buildTrie3 chooses the two block sizes with the fewest bytes.
func buildTrie3(v []int) trie3 {
	var best trie3
	bestSize := -1
	for s3 := 3; s3 <= 8; s3++ {
		var ids, data []int
		seen := map[string]int{}
		for lo := 0; lo < len(v); lo += 1 << s3 {
			key := fmt.Sprint(v[lo : lo+1<<s3])
			id, ok := seen[key]
			if !ok {
				id = len(data) >> s3
				seen[key] = id
				data = append(data, v[lo:lo+1<<s3]...)
			}
			ids = append(ids, id)
		}
		for s2 := 2; s2 <= 8; s2++ {
			if len(ids)%(1<<s2) != 0 {
				continue
			}
			tr := trie3{s2: s2, s3: s3, data: data}
			seen2 := map[string]int{}
			for lo := 0; lo < len(ids); lo += 1 << s2 {
				key := fmt.Sprint(ids[lo : lo+1<<s2])
				id, ok := seen2[key]
				if !ok {
					id = len(tr.i2) >> s2
					seen2[key] = id
					tr.i2 = append(tr.i2, ids[lo:lo+1<<s2]...)
				}
				tr.i1 = append(tr.i1, id)
			}
			if bestSize < 0 || tr.bytes() < bestSize {
				best, bestSize = tr, tr.bytes()
			}
		}
	}
	return best
}

// writeTrie3 writes a three-stage table: name + "Shift2", "Shift3",
// "Index1", "Index2" and "Data".
func writeTrie3(b *strings.Builder, name string, tr trie3) {
	fmt.Fprintf(b, "const %sShift2: u32 = %d\nconst %sShift3: u32 = %d\n\n", name, tr.s2, name, tr.s3)
	writeArray(b, name+"Index1", elemType(tr.i1), tr.i1, false)
	writeArray(b, name+"Index2", elemType(tr.i2), tr.i2, false)
	writeArray(b, name+"Data", "u8", tr.data, false)
}

// TestSTDTEXT_WordsTableBytes logs the static bytes of the generated tables
// (the audit row's table size).
func TestSTDTEXT_WordsTableBytes(t *testing.T) {
	d := needSeg(t)
	total := 256
	for _, p := range []struct {
		name string
		v    []uint8
	}{{"WordProp", d.wb}, {"SentProp", d.sb}} {
		v := make([]int, len(p.v))
		for c := range v {
			v[c] = int(p.v[c])
		}
		tr := buildTrie3(v)
		total += tr.bytes()
		t.Logf("%s: shifts %d and %d: %d + %d + %d entries = %d bytes", p.name, tr.s2, tr.s3, len(tr.i1), len(tr.i2), len(tr.data), tr.bytes())
	}
	t.Logf("with the two 128-byte ASCII tables: %d bytes", total)
}

// TestSTDTEXT_AsciiPremise checks what the ASCII steps of bounds.mk
// assume: no ASCII scalar is Extend, Format or ZWJ for Word_Break, Extend
// or Format for Sentence_Break, or Extended_Pictographic.
func TestSTDTEXT_AsciiPremise(t *testing.T) {
	d := needSeg(t)
	for c := 0; c < 0x80; c++ {
		w := d.wb[c]
		if w&wbExtPict != 0 || w == wbExtend || w == wbFormat || w == wbZWJ {
			t.Errorf("U+%04X: WordProp %#x", c, w)
		}
		if s := d.sb[c]; s == sbExtend || s == sbFormat {
			t.Errorf("U+%04X: Sentence_Break %s", c, sbNames[s])
		}
	}
}
