// Why: the float bit casts must agree bit for bit at compile time and run time,
// NaN payloads and subnormals included.
// What: TestCoreNew_BitsMatchGo, f64.Bits, f64.FromBits, f32.Bits and
// f32.FromBits against Go's math.Float64bits and math.Float32bits.
// How: a generated program folds FromBits, Bits and the negation in consts and
// computes them again at run time from unfoldable inputs; built dev and release.
//
// The negation is exact for every value that is not a NaN; of a NaN it must
// give a NaN, whose sign and payload the language leaves unspecified (the
// evaluator gives the canonical NaN, native code flips the sign bit).

package std

import (
	"fmt"
	"math"
	"strings"
	"testing"
)

// bitsCases64 and bitsCases32 are the encodings: every class boundary,
// NaN payloads in every position, and a seeded walk.
func bitsCases64() []uint64 {
	cs := []uint64{
		0, 1 << 63, 1, 0x000FFFFFFFFFFFFF, 0x0010000000000000, 0x3FF0000000000000,
		0x7FEFFFFFFFFFFFFF, 0x7FF0000000000000, 0xFFF0000000000000,
		0x7FF8000000000000, 0xFFF8000000000000, 0x7FF0000000000001, 0xFFF0000000000001,
		0x7FF4000000000000, 0x7FF7FFFFFFFFFFFF, 0x7FFFFFFFFFFFFFFF, 0xFFFFFFFFFFFFFFFF,
		0x7FF8000000000001, 0xFFF8DEADBEEF0001, 0x8000000000000001, 0x800FFFFFFFFFFFFF,
	}
	for i := 0; i < 52; i++ {
		cs = append(cs, 0x7FF0000000000000|1<<i, 0xFFF0000000000000|1<<i)
	}
	s := uint64(0x9E3779B97F4A7C15)
	for i := 0; i < 64; i++ {
		s = s*6364136223846793005 + 1442695040888963407
		cs = append(cs, s)
		if i%4 == 0 {
			cs = append(cs, s|0x7FF0000000000000) // inf or NaN, keeping the random payload
		}
	}
	return cs
}

func bitsCases32() []uint32 {
	cs := []uint32{
		0, 1 << 31, 1, 0x007FFFFF, 0x00800000, 0x3F800000, 0x7F7FFFFF, 0x7F800000, 0xFF800000,
		0x7FC00000, 0xFFC00000, 0x7F800001, 0xFF800001, 0x7FA00000, 0x7FBFFFFF, 0x7FFFFFFF,
		0xFFFFFFFF, 0x7FC00001, 0x80000001,
	}
	for i := 0; i < 23; i++ {
		cs = append(cs, 0x7F800000|1<<i, 0xFF800000|1<<i)
	}
	s := uint64(0x2545F4914F6CDD1D)
	for i := 0; i < 64; i++ {
		s = s*6364136223846793005 + 1442695040888963407
		cs = append(cs, uint32(s>>32))
		if i%4 == 0 {
			cs = append(cs, uint32(s>>32)|0x7F800000)
		}
	}
	return cs
}

func isNaN32(c uint32) bool {
	f := math.Float32frombits(c)
	return f != f
}

// bitsProgram writes the program: consts E (round trip) and G (the
// negated value's bits, or for a NaN whether the negation is a NaN) per
// encoding, then Main printing, per line, the const pair and then the
// run-time triple.
func bitsProgram(c64 []uint64, c32 []uint32) string {
	var b strings.Builder
	b.WriteString("// Generated by TestCoreNew_BitsMatchGo.\n\n")
	fmt.Fprintf(&b, "const In64: [%d]u64 = [", len(c64))
	for i, c := range c64 {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "0x%X", c)
	}
	b.WriteString("]\n\n")
	fmt.Fprintf(&b, "const In32: [%d]u32 = [", len(c32))
	for i, c := range c32 {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "0x%X", c)
	}
	b.WriteString("]\n\n")
	for i, c := range c64 {
		fmt.Fprintf(&b, "const E%d: u64 = f64.FromBits(0x%X).Bits()\n", i, c)
		if math.IsNaN(math.Float64frombits(c)) {
			fmt.Fprintf(&b, "const G%d: bool = NegNaN64(0x%X)\n", i, c)
		} else {
			fmt.Fprintf(&b, "const G%d: u64 = (-f64.FromBits(0x%X)).Bits()\n", i, c)
		}
	}
	for i, c := range c32 {
		fmt.Fprintf(&b, "const F%d: u32 = f32.FromBits(0x%X).Bits()\n", i, c)
		if isNaN32(c) {
			fmt.Fprintf(&b, "const H%d: bool = NegNaN32(0x%X)\n", i, c)
		} else {
			fmt.Fprintf(&b, "const H%d: u32 = (-f32.FromBits(0x%X)).Bits()\n", i, c)
		}
	}
	b.WriteString(`
// NegNaN64 and NegNaN32 say whether the negation of b's value is a NaN.
NegNaN64(b: u64): bool {
    y := -f64.FromBits(b)
    return y != y
}

NegNaN32(b: u32): bool {
    y := -f32.FromBits(b)
    return y != y
}

export Main(sys: &System): WriteError|ParseError!void {
    var out := sys.Stdout()
    k := Trunc[u64](try sys.args[1].ParseInt())
`)
	for i := range c64 {
		fmt.Fprintf(&b, "    try Print(mut out, \"{a} {b}\\n\", (a: E%d, b: G%d))\n", i, i)
	}
	for i := range c32 {
		fmt.Fprintf(&b, "    try Print(mut out, \"{a} {b}\\n\", (a: F%d, b: H%d))\n", i, i)
	}
	b.WriteString(`    for c in In64 {
        x := f64.FromBits(c ^ k)
        n := x != x
        if n {
            try Print(mut out, "{a} {b} {n}\n", (a: x.Bits(), b: NegNaN64(c ^ k), n))
        } else {
            try Print(mut out, "{a} {b} {n}\n", (a: x.Bits(), b: (-x).Bits(), n))
        }
    }
    for c in In32 {
        y := f32.FromBits(c ^ Trunc[u32](k))
        n := y != y
        if n {
            try Print(mut out, "{a} {b} {n}\n", (a: y.Bits(), b: NegNaN32(c ^ Trunc[u32](k)), n))
        } else {
            try Print(mut out, "{a} {b} {n}\n", (a: y.Bits(), b: (-y).Bits(), n))
        }
    }
}
`)
	return b.String()
}

// bitsModel is the expected output: Go's moves, the sign bit flipped for
// the negation of a value that is not a NaN, and "true" for a NaN's.
func bitsModel(c64 []uint64, c32 []uint32) string {
	neg64 := func(c uint64) string {
		if math.IsNaN(math.Float64frombits(c)) {
			return "true"
		}
		return fmt.Sprint(c ^ 1<<63)
	}
	neg32 := func(c uint32) string {
		if isNaN32(c) {
			return "true"
		}
		return fmt.Sprint(c ^ 1<<31)
	}
	var b strings.Builder
	for _, c := range c64 {
		fmt.Fprintf(&b, "%d %s\n", math.Float64bits(math.Float64frombits(c)), neg64(c))
	}
	for _, c := range c32 {
		fmt.Fprintf(&b, "%d %s\n", math.Float32bits(math.Float32frombits(c)), neg32(c))
	}
	for _, c := range c64 {
		x := math.Float64frombits(c)
		fmt.Fprintf(&b, "%d %s %t\n", math.Float64bits(x), neg64(c), math.IsNaN(x))
	}
	for _, c := range c32 {
		fmt.Fprintf(&b, "%d %s %t\n", math.Float32bits(math.Float32frombits(c)), neg32(c), isNaN32(c))
	}
	return b.String()
}

func TestCoreNew_BitsMatchGo(t *testing.T) {
	t.Parallel()
	c64, c32 := bitsCases64(), bitsCases32()
	src, want := bitsProgram(c64, c32), bitsModel(c64, c32)
	for _, prof := range [][]string{nil, {"--release"}} {
		exe := buildNative(t, nil, src, prof...)
		r := runNative(t, exe, "", "0")
		if r.code != 0 || r.stdout != want {
			t.Fatalf("%v: exit %d\nstderr: %s\n%s", prof, r.code, r.stderr, coreNewDiff(r.stdout, want))
		}
	}
}
